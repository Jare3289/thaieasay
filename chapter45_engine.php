 *      ด้วย ch45_ai_findings() ผู้วิจัยจึงรู้ว่าควรย่อไปในมุมไหน
 *   2) ย่อข้อความจากงานวิจัยที่ผู้วิจัย "วางมาให้" ให้เหลือ 1-2 ประโยค (ฟังก์ชันนี้)

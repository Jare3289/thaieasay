        '  "link_to_result":"กลุ่มนี้เกี่ยวข้องกับผลจริงของงานวิจัยนี้อย่างไร 1-2 ประโยค"}],',
        ' "paragraphs":["ย่อหน้าที่ 1 ของความเรียงประมวล","ย่อหน้าที่ 2", "..."],',
        ' "note":"ข้อสังเกตถึงผู้วิจัย เช่น คลังยังขาดงานเรื่องใด ถ้ามี"}',
    ]));

    if (mb_strlen($prompt, 'UTF-8') > CH45_MAX_PROMPT_CHARS) {
        return ['ok' => false, 'error' => 'คลังอ้างอิงยาวเกินกว่าที่จะประมวลได้ในครั้งเดียว — '
            . 'ลองย่อช่อง "สิ่งที่งานนี้ค้นพบโดยย่อ" ของรายการที่ยาวมากให้สั้นลง'];
    }

    $sys = implode("\n", [
        'คุณคือผู้ช่วยนักวิจัยที่ทำหน้าที่ "ประมวลงานวิจัยที่เกี่ยวข้อง" จากคลังที่ผู้ใช้ให้มาเท่านั้น',
        'ห้ามค้นหาเพิ่ม ห้ามนึกงานวิจัยจากความจำ และห้ามแต่งข้อค้นพบที่ไม่ปรากฏในคลังที่ให้มา',
        'ทุกข้อกล่าวอ้างต้องมีข้อความหลักฐานที่คัดมาคำต่อคำจากคลังกำกับเสมอ',
        'ตอบกลับเป็น JSON เพียงอย่างเดียว ห้ามมีข้อความอื่นนอกวงเล็บปีกกา ห้ามใส่ ```',
    ]);

    $res = ai_call_model($settings, $sys, $prompt);
    if (!$res['ok']) return ['ok' => false, 'error' => (string)$res['error']];

    $obj = ai_extract_json($res['text']);
    if (!is_array($obj)) return ['ok' => false, 'error' => 'คำตอบของระบบไม่ใช่รูปแบบ JSON ที่อ่านได้'];

    $warn = [];
    $validKeys = [];
    foreach ($findings as $f) $validKeys[$f['key']] = $f['heading'];

    // ---- 1) กลุ่มประเด็นร่วม + ตรวจหลักฐานทีละก้อน ----
    $themes = [];
    $usedLabels = [];
    foreach ((array)($obj['themes'] ?? []) as $t) {
        if (!is_array($t)) continue;
        $title = ch45_clean($t['title'] ?? '', 200);
        if ($title === '') continue;

        $members = [];
        foreach ((array)($t['members'] ?? []) as $m) {
            if (!is_array($m)) continue;
            $rawLabel = ch45_clean($m['label'] ?? '', 190);
            if ($rawLabel === '') continue;
            $hit = ch45_match_reference($rawLabel, $refs);
            if (!$hit) {
                // ด่านที่ 1 — งานที่ไม่มีในคลังต้องไม่หลุดออกไปถึงหน้าจอ
                $warn[] = 'ระบบอ้างถึงงาน "' . $rawLabel . '" ที่ไม่มีอยู่ในคลังอ้างอิง — ตัดออกจากบทประมวลแล้ว';
                continue;
            }
            // ด่านที่ 2 — ข้อความหลักฐานต้องคัดมาจากช่องของงานชิ้นนั้นจริง
            $quote = ch45_clean($m['quote'] ?? '', 400);
            $qn = ch45_normalize_for_match($quote);
            $sn = ch45_normalize_for_match($hit['key_finding']);
            $verified = ($qn !== '' && mb_strlen($qn, 'UTF-8') >= 6 && mb_strpos($sn, $qn, 0, 'UTF-8') !== false);
            if (!$verified) {
                $warn[] = 'ข้อความหลักฐานของ "' . $hit['citation_label'] . '" ไม่ตรงกับช่อง '
                        . '"สิ่งที่งานนี้ค้นพบ" ที่กรอกไว้ในคลัง — ต้องเปิดคลังตรวจสอบก่อนนำไปใช้';
            }
            $members[] = [
                'label'       => (string)$hit['citation_label'],
                'ref_id'      => (int)$hit['id'],
                'quote'       => $quote,
                'verified'    => $verified,
                'key_finding' => (string)$hit['key_finding'],
            ];
            $usedLabels[(string)$hit['citation_label']] = true;
        }
        if (!$members) {
            $warn[] = 'กลุ่มประเด็น "' . $title . '" ไม่เหลืองานที่ตรวจสอบได้เลย — ตัดออกจากบทประมวลแล้ว';
            continue;
        }

        $stance = (string)($t['stance'] ?? '');
        if (!isset($stances[$stance])) $stance = 'mixed';
        $fkey = ch45_clean($t['finding_key'] ?? '', 60);
        if ($fkey !== '' && !isset($validKeys[$fkey])) $fkey = '';

        $themes[] = [
            'title'          => $title,
            'stance'         => $stance,
            'stance_label'   => $stances[$stance],
            'finding_key'    => $fkey,
            'finding_head'   => $fkey !== '' ? $validKeys[$fkey] : '',
            'members'        => $members,
            'agreement'      => ch45_clean($t['agreement'] ?? '', 800),
            'difference'     => ch45_clean($t['difference'] ?? '', 800),
            'link_to_result' => ch45_clean($t['link_to_result'] ?? '', 800),
        ];
    }
    if (!$themes) {
        return ['ok' => false, 'error' => 'ระบบประมวลแล้วไม่เหลือกลุ่มประเด็นที่ตรวจสอบได้เลย — '
            . 'ลองตรวจว่าช่อง "สิ่งที่งานนี้ค้นพบโดยย่อ" ของแต่ละรายการในคลังเขียนสาระไว้ครบหรือยัง'];
    }

    // ---- 2) ความเรียงประมวล + ด่านที่ 3 และ 4 ----
    $allLabels = [];
    foreach ($refs as $r) $allLabels[] = (string)$r['citation_label'];
    $sourceNums = [];
    foreach ($findings as $f) $sourceNums = array_merge($sourceNums, ch45_numbers_in($f['summary']));
    foreach ($refs as $r) $sourceNums = array_merge($sourceNums, ch45_numbers_in($r['key_finding']),
                                                    ch45_numbers_in($r['citation_label']));
    $sourceNums = array_values(array_unique($sourceNums));

    $paragraphs = [];
    foreach ((array)($obj['paragraphs'] ?? []) as $p) {
        $text = ch45_clean($p, 3000);
        if ($text === '') continue;
        $suspect = ch45_detect_uncited_citation($text, implode(' ', $allLabels), $refs);
        if ($suspect) {
            $warn[] = 'ความเรียงประมวลมีร่องรอยการอ้างอิงงานที่ไม่อยู่ในคลัง — ตรวจย่อหน้าที่ขึ้นกรอบแดงก่อนใช้';
        }
        $badNums = [];
        foreach (ch45_numbers_in($text) as $n) {
            if (!in_array($n, $sourceNums, true)) $badNums[] = $n;
        }
        if ($badNums) {
            $warn[] = 'ความเรียงประมวลมีตัวเลข ' . implode(', ', $badNums)
                    . ' ซึ่งไม่พบทั้งในผลจริงและในคลังอ้างอิง — ตรวจสอบก่อนนำไปใช้';
        }
        $paragraphs[] = ['text' => $text, 'suspect' => $suspect, 'bad_numbers' => $badNums];
    }
    if (!$paragraphs) $warn[] = 'ระบบยังไม่ได้เขียนความเรียงประมวลกลับมา — มีเฉพาะการจัดกลุ่มเท่านั้น';

    // ---- 3) ช่องว่างของคลัง — คำนวณเองจากตารางความสัมพันธ์ ไม่ให้ AI ตอบ ----
    // "ยังไม่มีงานรองรับ" นับจากช่อง "ประเด็นที่งานนี้ใช้จับคู่" ที่ผู้วิจัยตั้งไว้จริงเท่านั้น
    // แต่ถ้าบทประมวลเห็นว่ามีงานในคลังที่น่าจะตรงกับประเด็นนั้น ให้เสนอชื่อไว้ข้าง ๆ
    // ผู้วิจัยจะได้กลับไปตั้งค่า "ประเด็นที่จับคู่" ให้งานชิ้นนั้นเอง (ระบบไม่ตั้งให้เอง)
    $suggestByKey = [];
    foreach ($themes as $th) {
        if ($th['finding_key'] === '') continue;
        foreach ($th['members'] as $mb) {
            if (!$mb['verified']) continue;
            $suggestByKey[$th['finding_key']][$mb['label']] = true;
        }
    }
    $gaps = [];
    foreach ($matrix['rows'] as $row) {
        if ($row['refs']) continue;
        $gaps[] = ['finding_key' => $row['key'], 'heading' => $row['heading'],
                   'summary' => $row['summary'], 'genre_bound' => $row['genre_bound'],
                   'suggested' => array_keys($suggestByKey[$row['key']] ?? [])];
    }
    $orphans = [];
    foreach ($matrix['unassigned'] as $u) {
        if (!isset($usedLabels[$u['label']])) $orphans[] = $u['label'];
    }
    if ($orphans) {
        $warn[] = 'งานในคลังที่ยังไม่ถูกจัดเข้ากลุ่มประเด็นใดเลย: ' . implode(' · ', $orphans)
                . ' — ถ้าเป็นงานที่เกี่ยวข้องจริง ลองระบุ "ประเด็นที่งานนี้ใช้จับคู่" ให้ชัดขึ้นแล้วประมวลใหม่';
    }

    $note = ch45_clean($obj['note'] ?? '', 800);
    if ($note !== '') $warn[] = $note;

    return ['ok' => true, 'error' => '', 'raw' => $res['text'],
            'payload' => [
                'themes'     => $themes,
                'paragraphs' => $paragraphs,
                'gaps'       => $gaps,
                'matrix'     => $matrix,
                'note'       => $note,
                'ref_count'  => count($refs),
            ],
            'warnings' => array_values(array_unique($warn))];
}


/** อ่านผลวิเคราะห์ที่เก็บไว้ทั้งหมด (คีย์ = job_key) */
function ch45_results(PDO $pdo) {
    $out = [];
    try {
        foreach ($pdo->query('SELECT * FROM ch45_analysis')->fetchAll() as $row) {
            $payload = json_decode((string)$row['payload'], true);
            $out[(string)$row['job_key']] = [
                'job_key'    => (string)$row['job_key'],
                'payload'    => is_array($payload) ? $payload : [],
                'provider'   => (string)($row['provider'] ?? ''),
                'model'      => (string)($row['model'] ?? ''),
                'input_hash' => (string)($row['input_hash'] ?? ''),
                'warnings'   => json_decode((string)($row['warnings'] ?? ''), true) ?: [],
                'updated_at' => (string)($row['updated_at'] ?? ''),
            ];
        }
    } catch (Exception $e) { /* ยังไม่มีตาราง */ }
    return $out;
}

/** บันทึกผลวิเคราะห์ของชิ้นงานหนึ่ง (ทำซ้ำจะทับของเดิม) */
function ch45_save_result(PDO $pdo, $jobKey, array $payload, array $info = []) {
    $stmt = $pdo->prepare('INSERT INTO ch45_analysis
        (job_key, payload, raw_response, provider, model, requested_by, input_hash, warnings)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        ON DUPLICATE KEY UPDATE payload = VALUES(payload), raw_response = VALUES(raw_response),
            provider = VALUES(provider), model = VALUES(model), requested_by = VALUES(requested_by),
            input_hash = VALUES(input_hash), warnings = VALUES(warnings)');
    $stmt->execute([
        $jobKey,
        json_encode($payload, JSON_UNESCAPED_UNICODE),
        (string)($info['raw'] ?? ''),
        (string)($info['provider'] ?? ''),
        (string)($info['model'] ?? ''),
        (string)($info['by'] ?? ''),
        (string)($info['input_hash'] ?? ''),
        json_encode(array_values($info['warnings'] ?? []), JSON_UNESCAPED_UNICODE),
    ]);
}

/** ลบผลวิเคราะห์ของชิ้นงานหนึ่ง */
function ch45_delete_result(PDO $pdo, $jobKey) {
    $stmt = $pdo->prepare('DELETE FROM ch45_analysis WHERE job_key = ?');
    $stmt->execute([$jobKey]);
    return $stmt->rowCount() > 0;
}

/**
 * ลายนิ้วมือของข้อมูลนำเข้า — ใช้บอกว่าผลวิเคราะห์ที่เก็บไว้ "ล้าสมัย" หรือยัง
 * (คะแนนหรือเรียงความเปลี่ยนหลังวิเคราะห์ไปแล้ว ระบบจะขึ้นเตือนให้วิเคราะห์ใหม่)
 */
function ch45_input_hash(array $ds, array $quant, array $defects) {
    $sig = [
        'n' => $quant['n'],
        'rows' => array_map(function ($r) {
            return [$r['key'], round((float)$r['pre_mean'], 4), round((float)$r['post_mean'], 4)];
        }, $quant['rows']),
        'defects' => array_map(function ($r) { return [$r['id'], $r['n1'], $r['n2']]; },
                               array_values($defects['rows'])),
        'work' => [$ds['meta']['work1_phase'], $ds['meta']['work2_phase']],
        'cut'  => $ds['meta']['defect_cut'],
    ];
    return sha1(json_encode($sig));
}


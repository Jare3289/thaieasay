    if (!$findings) {
        $L[] = '(ยังไม่มีประเด็น — ให้ย่อสาระสำคัญของงานนี้ตามที่ต้นฉบับบอกไว้)';
    } else {
        foreach ($findings as $f) {
            $L[] = '- [' . $f['key'] . '] ' . $f['heading'] . ' — ' . $f['summary'];
        }
    }
    if ($preferKey !== '') $L[] = 'ผู้วิจัยระบุว่าอยากให้ย่อในมุมของประเด็น [' . ch45_clean($preferKey, 60) . ']';
    $L[] = '';

    $prompt = implode("\n", array_merge($L, [
        '=== สิ่งที่ต้องเขียน ===',
        'ย่อ "สิ่งที่งานวิจัยชิ้นนี้ค้นพบ" ให้เหลือ 1-2 ประโยคภาษาไทย สำหรับกรอกลงคลังอ้างอิง',
        'เขียนเป็นประโยคบอกเล่าที่อ่านจบได้ในตัวเอง ขึ้นต้นทำนองว่า "พบว่า..." หรือ "เสนอว่า..."',
        'ถ้าเลือกมุมที่ตรงกับประเด็นใดประเด็นหนึ่งข้างต้นได้ ให้ย่อในมุมนั้น เพื่อให้จับคู่กับผลจริงได้ง่าย',
        '',
        'กติกาที่ห้ามฝ่าฝืน:',
        '1. ใช้ได้เฉพาะสาระที่ปรากฏในข้อความต้นฉบับข้างต้นเท่านั้น',
        '   ห้ามเติมตัวเลข ชื่อผู้แต่ง ปีที่พิมพ์ ชื่อทฤษฎี หรือข้อค้นพบที่ไม่มีในต้นฉบับโดยเด็ดขาด',
        '2. ห้ามนำผลของงานวิจัยผู้วิจัย (ประเด็นที่ให้ไว้ข้างต้น) มาเขียนเป็นข้อค้นพบของงานชิ้นนี้',
        '   ประเด็นเหล่านั้นมีไว้ให้เลือกมุมเท่านั้น',
        '3. ถ้าข้อความต้นฉบับไม่ได้บอกผลการวิจัยไว้เลย (เช่น มีแต่ชื่อเรื่องหรือวัตถุประสงค์)',
        '   ให้ตอบ key_finding เป็นสตริงว่าง และบอกใน note ว่าต้องการข้อความส่วนใดเพิ่ม',
        '4. เขียนด้วยถ้อยคำของผู้วิจัยเอง (ถอดความ) ไม่ใช่คัดลอกยาว ๆ มาทั้งย่อหน้า',
        '',
        'ตอบเป็น JSON รูปแบบนี้เท่านั้น:',
        '{"key_finding":"1-2 ประโยค","finding_key":"คีย์ของประเด็นที่ตรงที่สุด หรือสตริงว่างถ้าไม่ตรงกับประเด็นใดเลย",'
            . '"related":true หรือ false,"note":"ข้อสังเกตถึงผู้วิจัย ถ้ามี"}',
    ]));

    $sys = implode("\n", [
        'คุณคือผู้ช่วยนักวิจัยที่ทำหน้าที่ "ย่อความ" จากข้อความที่ผู้ใช้นำมาให้เท่านั้น',

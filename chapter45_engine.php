/**
 * ตารางความสัมพันธ์ระหว่าง "ประเด็นจากผลจริง" กับ "งานในคลังอ้างอิง"
 * คำนวณจากข้อมูลจริงล้วน ๆ ไม่ผ่านระบบ AI — ใช้เป็นฐานที่เชื่อถือได้ของบทประมวล
 * และใช้ตรวจทานคำตอบของ AI ว่าบอกช่องว่างของคลังตรงกับความจริงหรือไม่
 */
function ch45_reference_matrix(array $findings, array $refs) {
    $rows = [];
    $known = [];
    foreach ($findings as $f) {
        $known[$f['key']] = true;
        $rows[$f['key']] = [
            'key'         => $f['key'],
            'heading'     => $f['heading'],
            'summary'     => $f['summary'],
            'genre_bound' => !empty($f['genre_bound']),
            'refs'        => [],
        ];
    }
    $unassigned = [];
    foreach ($refs as $r) {
        $item = [
            'id'          => (int)($r['id'] ?? 0),
            'label'       => (string)($r['citation_label'] ?? ''),
            'key_finding' => (string)($r['key_finding'] ?? ''),
            'source_type' => (string)($r['source_type'] ?? 'other'),
            'source_url'  => (string)($r['source_url'] ?? ''),
        ];
        $fk = (string)($r['finding_key'] ?? '');
        if ($fk !== '' && isset($known[$fk])) $rows[$fk]['refs'][] = $item;
        else $unassigned[] = $item;
    }
    $covered = 0;
    foreach ($rows as $row) if ($row['refs']) $covered++;

    return [
        'rows'       => array_values($rows),
        'unassigned' => $unassigned,
        'total_refs' => count($refs),
        'findings'   => count($rows),
        'covered'    => $covered,
        'missing'    => count($rows) - $covered,
    ];
}

/**
 * ลายนิ้วมือของ "ผลจริง + คลังอ้างอิง" ที่ใช้ประมวล
 * ใช้บอกว่าบทประมวลที่เก็บไว้ล้าสมัยหรือยัง (เพิ่ม/แก้ไข/ลบรายการในคลังแล้วต้องประมวลใหม่)
 * แยกจาก ch45_input_hash() เพราะบทประมวลไม่ได้ขึ้นกับคะแนนรายคนเหมือนความเรียงบทที่ 4
 */
function ch45_reference_synthesis_hash(array $findings, array $refs) {
    $sig = [];
    foreach ($findings as $f) $sig[] = $f['key'] . '|' . $f['summary'];
    foreach ($refs as $r) {
        $sig[] = (int)($r['id'] ?? 0) . '|' . (string)($r['citation_label'] ?? '')
               . '|' . (string)($r['key_finding'] ?? '') . '|' . (string)($r['finding_key'] ?? '');
    }
    return md5(implode("\n", $sig));
}

/** หาว่าป้ายอ้างอิงที่ระบบตอบกลับมาตรงกับรายการใดในคลัง (เทียบแบบตัดช่องว่าง/อักขระคั่นออก) */
function ch45_match_reference($label, array $refs) {
    $n = ch45_normalize_for_match($label);
    if ($n === '') return null;
    foreach ($refs as $r) {
        if (ch45_normalize_for_match($r['citation_label']) === $n) return $r;
    }
    // ป้ายที่ตอบกลับมาอาจตัดคำหน้า/หลังไปบ้าง — ยอมรับได้ถ้าเป็นส่วนหนึ่งของกันและกันจริง
    foreach ($refs as $r) {
        $rn = ch45_normalize_for_match($r['citation_label']);
        if ($rn !== '' && mb_strlen($n, 'UTF-8') >= 4
            && (mb_strpos($rn, $n, 0, 'UTF-8') !== false || mb_strpos($n, $rn, 0, 'UTF-8') !== false)) {
            return $r;
        }
    }
    return null;
}


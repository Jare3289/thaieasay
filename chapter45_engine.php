/**
 * ลำดับ "ตอนสั่งทำ" — เรียงจาก deps ด้วย topological sort
 * (ลำดับในหน้าจอเป็นลำดับของวิทยานิพนธ์ ส่วนลำดับนี้คือลำดับที่สั่งได้โดยไม่ข้ามชิ้นงานที่ต้องมีก่อน)
 */
function ch45_ai_jobs_run_order() {
    $jobs   = ch45_ai_jobs();
    $order  = [];
    $placed = [];

    $visit = function ($key, $stack) use (&$visit, $jobs, &$order, &$placed) {
        if (isset($placed[$key]) || !isset($jobs[$key]) || isset($stack[$key])) return;
        $stack[$key] = true;
        foreach ($jobs[$key]['deps'] as $dep) $visit($dep, $stack);
        $placed[$key] = true;
        $order[] = $key;
    };
    foreach (array_keys($jobs) as $k) $visit($k, []);

    return $order;
}


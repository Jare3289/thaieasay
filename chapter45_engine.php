/** แปลงตาราง 12 เป็นข้อความสำหรับใส่ในคำสั่ง */
function ch45_ai_quant_block(array $quant) {
    $L = ['=== ตาราง 12 ผลการเปรียบเทียบก่อนเรียน–หลังเรียน (n = ' . $quant['n'] . ', df = ' . $quant['df'] . ') ==='];
    foreach ($quant['rows'] as $r) {
        $L[] = sprintf(
            '%s (คะแนนเต็ม %s): ก่อนเรียน M = %s, SD = %s (คิดเป็นร้อยละ %s) | หลังเรียน M = %s, SD = %s (ร้อยละ %s) '
            . '| ผลต่างเฉลี่ย %s | t = %s | p %s | Cohen\'s dz = %s (%s)',
            $r['label'], ch45_fmt($r['max'], 0),
            ch45_fmt($r['pre_mean']), ch45_fmt($r['pre_sd']), ch45_fmt($r['pre_pct']),
            ch45_fmt($r['post_mean']), ch45_fmt($r['post_sd']), ch45_fmt($r['post_pct']),
            ch45_fmt($r['gain']), ch45_fmt($r['t'], 3),
            (($r['p'] !== null && $r['p'] < 0.001) ? '< .001' : '= ' . ch45_fmt_p($r['p'])),
            ch45_fmt($r['dz']), $r['effect']
        );
    }
    $L[] = '';
    $L[] = 'ลำดับด้านที่เปลี่ยนแปลงมากไปน้อย (เรียงตามขนาดอิทธิพล):';
    foreach ($quant['ranking'] as $r) {
        $L[] = sprintf('  อันดับ %d %s — ร้อยละของคะแนนเต็มเพิ่มจาก %s เป็น %s (dz = %s)',
            $r['rank'], $r['label'], ch45_fmt($r['pre_pct']), ch45_fmt($r['post_pct']), ch45_fmt($r['dz']));
    }

    $n = $quant['normality']['overall'] ?? null;
    if ($n && $n['W'] !== null) {
        $L[] = '';
        $L[] = 'ผลทดสอบการแจกแจงปกติของคะแนนผลต่าง (Shapiro-Wilk) ภาพรวม: W = ' . ch45_fmt_r($n['W'])
             . ', p = ' . ch45_fmt_p($n['p'])
             . ($n['normal'] ? ' (ไม่แตกต่างจากการแจกแจงปกติ)' : ' (แตกต่างจากการแจกแจงปกติอย่างมีนัยสำคัญ)');
    }

    if (!empty($quant['interrater'])) {
        $L[] = '';
        $L[] = 'ความเที่ยงระหว่างผู้ประเมิน:';
        foreach ($quant['interrater'] as $ir) {
            $parts = [];
            foreach ($ir['pearson'] as $pr) $parts[] = 'r = ' . ch45_fmt_r($pr['r']);
            $L[] = '  รอบ' . $ir['label'] . ' (ผู้ประเมิน ' . $ir['k'] . ' คน, n = ' . $ir['n'] . '): '
                 . implode(', ', $parts) . ' | ICC = ' . ch45_fmt_r($ir['icc']['iccK']) . ' (' . $ir['icc_label'] . ')';
        }
    }
    $L[] = '';
    return implode("\n", $L);
}

/** แปลงตาราง 14 เป็นข้อความสำหรับใส่ในคำสั่ง */
function ch45_ai_defect_block(array $defects, $onlyIndicator = null) {
    $L = ['=== ตาราง 14 จำนวนและร้อยละของนักเรียนที่ปรากฏข้อบกพร่อง (n = ' . $defects['n'] . ') ==='];
    foreach ($defects['rows'] as $id => $r) {
        if ($onlyIndicator !== null && $id !== $onlyIndicator) continue;
        $L[] = sprintf('%d. [%s %s] %s — ครั้งที่ 1: %d คน (ร้อยละ %s) | ครั้งที่ 2: %d คน (ร้อยละ %s) | เปลี่ยนแปลง %s จุดร้อยละ',
            $r['no'], $r['id'], $r['name'], $r['defect'],
            $r['n1'], ch45_fmt($r['pct1']), $r['n2'], ch45_fmt($r['pct2']),
            ($r['diff_pct'] === null ? '—' : (($r['diff_pct'] > 0 ? '+' : '') . ch45_fmt($r['diff_pct']))));
        if ($onlyIndicator !== null) {
            $L[] = sprintf('   คะแนนดิบเฉลี่ยของตัวบ่งชี้นี้ (เต็ม 4): ครั้งที่ 1 = %s, ครั้งที่ 2 = %s',
                ch45_fmt($r['mean1']), ch45_fmt($r['mean2']));
            $L[] = sprintf('   นักเรียนที่ครั้งที่ 1 มีข้อบกพร่องแล้วครั้งที่ 2 แก้ได้: %d คน | ยังคงมีอยู่: %d คน | เกิดขึ้นใหม่ในครั้งที่ 2: %d คน',
                count($r['resolved']), count($r['persist']), count($r['emerged']));
            $L[] = '   เกณฑ์การให้คะแนนตัวบ่งชี้นี้: ' . (ch45_indicators()[$id]['guide'] ?? '');
        }
    }
    if ($onlyIndicator === null) {
        $L[] = '';
        $mi = $defects['most_improved']; $li = $defects['least_improved'];
        if ($mi) $L[] = 'ตัวบ่งชี้ที่จำนวนผู้มีข้อบกพร่องลดลงมากที่สุด: ' . $mi['name']
             . ' (จากร้อยละ ' . ch45_fmt($mi['pct1']) . ' เหลือร้อยละ ' . ch45_fmt($mi['pct2']) . ')';
        if ($li) $L[] = 'ตัวบ่งชี้ที่ลดลงน้อยที่สุด: ' . $li['name']
             . ' (จากร้อยละ ' . ch45_fmt($li['pct1']) . ' เหลือร้อยละ ' . ch45_fmt($li['pct2']) . ')';
        $L[] = 'ภาพรวม: จำนวนผู้มีข้อบกพร่องลดลง ' . $defects['summary_phrase'];
    }
    $L[] = '';
    return implode("\n", $L);
}

/** แปลงคลังผลงานจริงเป็นข้อความสำหรับใส่ในคำสั่ง */
function ch45_ai_evidence_block(array $ev, array $meta) {
    $L = ['=== ผลงานจริงของนักเรียนที่คัดมาให้เลือกยกเป็นตัวอย่าง ===',
          'ยกข้อความจากผลงานเหล่านี้เท่านั้น คัดลอกคำต่อคำ ห้ามแก้ไขหรือขัดเกลา'];
    foreach (['work1' => $meta['work1_label'], 'work2' => $meta['work2_label']] as $slot => $label) {
        $L[] = '';
        $L[] = '--- ' . $label . ' ---';
        if (empty($ev[$slot])) { $L[] = '(ไม่พบผลงานที่บันทึกไว้ในรอบนี้)'; continue; }
        foreach ($ev[$slot] as $c) {
            $L[] = '[นักเรียนคนที่ ' . $c['no'] . '] คะแนนดิบตัวบ่งชี้นี้ = '
                 . ($c['raw'] === null ? '—' : ch45_fmt($c['raw'], 1)) . ' จาก 4 · ' . $c['tag']
                 . ' · ความยาว ' . $c['words'] . ' คำ';
            if (trim($c['intro']) !== '')      $L[] = '  ส่วนนำ: ' . $c['intro'];
            foreach ($c['body'] as $i => $p)   $L[] = '  เนื้อเรื่องย่อหน้าที่ ' . ($i + 1) . ': ' . $p;
            if (trim($c['conclusion']) !== '') $L[] = '  ส่วนสรุป: ' . $c['conclusion'];
        }
    }
    $L[] = '';
    return implode("\n", $L);
}

/**
 * สร้างรายการ "ประเด็นที่ควรอภิปราย" จากผลจริงที่คำนวณได้เท่านั้น (ไม่ใช่ข้อสันนิษฐานที่เขียนตายตัวไว้)
 * งานวิจัยแต่ละชุดข้อมูลจะได้ประเด็นไม่เท่ากันและไม่เหมือนกัน ขึ้นอยู่กับรูปแบบของผลจริงที่พบ
 *
 * แต่ละประเด็นมี:
 *   key         รหัสอ้างอิงประเด็น (คงที่ ใช้ผูกกับผลวิเคราะห์เดิมได้)
 *   heading     หัวข้อสั้น ๆ ของประเด็น
 *   summary     ประโยคข้อเท็จจริงที่ประกอบจากตัวเลขจริงล้วน ๆ (ระบบไม่ได้ "คิด" ตัวเลขใด ๆ เพิ่ม)
 *   genre_bound true = ตัวบ่งชี้นี้ผูกกับประเภทงานเขียน ต้องกำกับการตีความในคำสั่งที่ส่งให้ระบบ
 */
function ch45_ai_findings(array $quant, array $defects) {
    $out = [];
    $domains = ch45_domains();

    // 1) ภาพรวม — มีเสมอถ้าคำนวณตาราง 12 ได้
    $overall = $quant['by_key']['overall'] ?? null;
    if ($overall && $overall['pre_mean'] !== null && $overall['post_mean'] !== null) {
        $out[] = [
            'key' => 'overall',
            'heading' => 'ผลรวมความสามารถในการเขียนเรียงความหลังเรียนสูงกว่าก่อนเรียน',
            'summary' => 'คะแนนรวมหลังเรียน (M = ' . ch45_fmt($overall['post_mean']) . ', SD = ' . ch45_fmt($overall['post_sd'])
                . ') สูงกว่าก่อนเรียน (M = ' . ch45_fmt($overall['pre_mean']) . ', SD = ' . ch45_fmt($overall['pre_sd']) . ') '
                . (!empty($overall['sig']) ? 'อย่างมีนัยสำคัญทางสถิติที่ระดับ .05' : 'แต่ไม่ถึงระดับนัยสำคัญทางสถิติที่ .05')
                . ' (t = ' . ch45_fmt($overall['t'], 3) . ', dz = ' . ch45_fmt($overall['dz']) . ', ' . $overall['effect'] . ')',
            'genre_bound' => false,
        ];
    }

    // 2) ด้านที่เปลี่ยนแปลงมากที่สุด/น้อยที่สุด (จากอันดับตามขนาดอิทธิพลที่คำนวณไว้แล้ว)
    $ranking = $quant['ranking'] ?? [];
    if ($ranking) {
        $top = $ranking[0];
        $bottom = $ranking[count($ranking) - 1];
        $out[] = [
            'key' => 'domain_top',
            'heading' => 'ด้าน' . $top['label'] . ' เปลี่ยนแปลงมากที่สุดในบรรดา 4 องค์ประกอบ',
            'summary' => 'ด้าน' . $top['label'] . ' มีขนาดอิทธิพล dz = ' . ch45_fmt($top['dz'])
                . ' (ร้อยละของคะแนนเต็มเพิ่มจาก ' . ch45_fmt($top['pre_pct']) . ' เป็น ' . ch45_fmt($top['post_pct']) . ')'
                . ' สูงที่สุดในบรรดาองค์ประกอบทั้งหมด',
            'genre_bound' => false,
        ];
        if ($bottom['key'] !== $top['key']) {
            $out[] = [
                'key' => 'domain_bottom',
                'heading' => 'ด้าน' . $bottom['label'] . ' เปลี่ยนแปลงน้อยที่สุดในบรรดา 4 องค์ประกอบ',
                'summary' => 'ด้าน' . $bottom['label'] . ' มีขนาดอิทธิพล dz = ' . ch45_fmt($bottom['dz'])
                    . ' (ร้อยละของคะแนนเต็มเพิ่มจาก ' . ch45_fmt($bottom['pre_pct']) . ' เป็น ' . ch45_fmt($bottom['post_pct']) . ')'
                    . ' ต่ำที่สุดในบรรดาองค์ประกอบทั้งหมด',
                'genre_bound' => false,
            ];
        }
    }

    // 3) ตัวบ่งชี้ที่ลดจำนวนผู้มีข้อบกพร่องได้มากที่สุด/น้อยที่สุด (ตาราง 14)
    $mi = $defects['most_improved'] ?? null;
    $li = $defects['least_improved'] ?? null;
    if ($mi) {
        $out[] = [
            'key' => 'defect_most',
            'heading' => 'ตัวบ่งชี้ที่จำนวนผู้มีข้อบกพร่องลดลงมากที่สุด: ' . $mi['name'],
            'summary' => $mi['name'] . ' มีผู้มีข้อบกพร่องลดลงจากร้อยละ ' . ch45_fmt($mi['pct1'])
                . ' เหลือร้อยละ ' . ch45_fmt($mi['pct2'])
                . ($mi['diff_pct'] !== null ? ' (ลดลง ' . ch45_fmt(abs((float)$mi['diff_pct'])) . ' จุดร้อยละ)' : ''),
            'genre_bound' => (bool)$mi['genre_bound'],
        ];
    }
    if ($li && (!$mi || $li['id'] !== $mi['id'])) {
        $worse = ($li['diff_pct'] !== null && $li['diff_pct'] > 0);
        $out[] = [
            'key' => 'defect_least',
            'heading' => 'ตัวบ่งชี้ที่จำนวนผู้มีข้อบกพร่องลดลงน้อยที่สุด: ' . $li['name'],
            'summary' => $li['name'] . ' มีผู้มีข้อบกพร่องเปลี่ยนจากร้อยละ ' . ch45_fmt($li['pct1'])
                . ' เป็นร้อยละ ' . ch45_fmt($li['pct2'])
                . ($li['diff_pct'] === null ? ''
                    : ($worse ? ' (เพิ่มขึ้น ' . ch45_fmt($li['diff_pct']) . ' จุดร้อยละ ซึ่งสวนทางกับตัวบ่งชี้อื่นที่ลดลง)'
                              : ' (ลดลงเพียง ' . ch45_fmt(abs((float)$li['diff_pct'])) . ' จุดร้อยละ ซึ่งน้อยกว่าตัวบ่งชี้อื่นอย่างเห็นได้ชัด)')),
            'genre_bound' => (bool)$li['genre_bound'],
        ];
    }

    // 4) ตัวบ่งชี้ที่ผูกกับประเภทงานเขียน — รายงานแยกเสมอเพราะตีความต่างจากตัวบ่งชี้อื่น
    //    (ข้ามตัวที่ถูกหยิบไปเป็นประเด็น most/least improved แล้วเพื่อไม่ให้ซ้ำ)
    $already = array_filter([$mi['id'] ?? null, $li['id'] ?? null]);
    foreach ($defects['rows'] as $id => $r) {
        if (!$r['genre_bound'] || in_array($id, $already, true)) continue;
        $out[] = [
            'key' => 'genre_' . str_replace('.', '_', $id),
            'heading' => 'ตัวบ่งชี้ที่ผูกกับประเภทงานเขียน: ' . $r['name'],
            'summary' => $r['name'] . ' มีผู้มีข้อบกพร่องเปลี่ยนจากร้อยละ ' . ch45_fmt($r['pct1'])
                . ' เป็นร้อยละ ' . ch45_fmt($r['pct2'])
                . ' ทั้งนี้ตัวบ่งชี้นี้ได้รับอิทธิพลจากประเภทของงานเขียนโดยตรง',
            'genre_bound' => true,
        ];
    }

    // 5) ตัวบ่งชี้ที่เปลี่ยนแปลงต่างจากตัวบ่งชี้อื่นในองค์ประกอบเดียวกันอย่างเห็นได้ชัด
    //    (เฉพาะตัวที่ไม่ผูกกับประเภทงานเขียน เพราะกรณีนั้นอธิบายได้อยู่แล้วในข้อ 4)
    foreach ($domains as $dk => $d) {
        $vals = [];
        foreach ($d['indicators'] as $id) {
            $r = $defects['rows'][$id] ?? null;
            if (!$r || $r['genre_bound'] || $r['diff_pct'] === null) continue;
            // ตัวบ่งชี้ที่ไม่มีใครปรากฏข้อบกพร่องเลยทั้งสองครั้ง (n1 = n2 = 0) ไม่ใช่กรณี "เปลี่ยนแปลงน้อยกว่าตัวอื่น"
            // แต่คือ "ไม่เคยเป็นปัญหา" จึงไม่ควรถูกดึงเข้ามาเทียบเป็นตัวบ่งชี้ที่เปลี่ยนแปลงน้อย
            if ((int)$r['n1'] === 0 && (int)$r['n2'] === 0) continue;
            $vals[$id] = (float)$r['diff_pct'];
        }
        if (count($vals) < 2) continue;
        foreach ($vals as $id => $dp) {
            $others = array_diff_key($vals, [$id => 0]);
            if (!$others) continue;
            $avgOthers = array_sum($others) / count($others);
            // diff_pct เป็นลบ = ผู้มีข้อบกพร่องลดลง (ดีขึ้น) — ถ้าตัวนี้ดีขึ้นน้อยกว่าค่าเฉลี่ยของตัวอื่นในด้านเดียวกัน
            // เกิน 15 จุดร้อยละ ถือว่าต่างจากตัวบ่งชี้อื่นในด้านเดียวกันอย่างเห็นได้ชัด ควรหยิบมาอภิปรายแยก
            if (($dp - $avgOthers) > 15) {
                $r = $defects['rows'][$id];
                $out[] = [
                    'key' => 'outlier_' . str_replace('.', '_', $id),
                    'heading' => 'ตัวบ่งชี้ ' . $r['name'] . ' เปลี่ยนแปลงน้อยกว่าตัวบ่งชี้อื่นในด้านเดียวกันอย่างเห็นได้ชัด',
                    'summary' => $r['name'] . ' เปลี่ยนแปลง ' . ch45_fmt($dp) . ' จุดร้อยละ ขณะที่ตัวบ่งชี้อื่นในด้าน' . $d['name']
                        . ' เปลี่ยนแปลงเฉลี่ย ' . ch45_fmt($avgOthers) . ' จุดร้อยละ',
                    'genre_bound' => false,
                ];
            }
        }
    }

    return $out;
}

/**
 * ช่วยผู้วิจัยเขียนช่อง "สิ่งที่งานนี้ค้นพบโดยย่อ" ของคลังอ้างอิง
 * -------------------------------------------------------------------------
 * ช่องนี้เขียนยากเพราะต้องย่อสาระของงานวิจัยหนึ่งชิ้นให้เหลือ 1-2 ประโยค
 * และต้องย่อ "ในมุมที่ตรงกับประเด็นที่พบจริงในงานวิจัยนี้" ระบบจึงช่วยได้ 2 ทาง

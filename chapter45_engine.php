/**
 * สั่งวิเคราะห์ชิ้นงานหนึ่ง แล้วบันทึกผลลงฐานข้อมูล
 * คืน ['ok' => bool, 'error' => ..., 'payload' => ..., 'warnings' => [...]]
 */
function ch45_ai_run(PDO $pdo, $jobKey, array $ctx, array $who) {
    $jobs = ch45_ai_jobs();
    if (!isset($jobs[$jobKey])) return ['ok' => false, 'error' => 'ไม่รู้จักชิ้นงานที่สั่ง'];

    $settings = ai_settings($pdo);
    if (!$settings['enabled'])    return ['ok' => false, 'error' => 'คุณครูปิดการใช้งานระบบตรวจอัตโนมัติไว้'];
    if (!$settings['configured']) return ['ok' => false, 'error' => 'ยังไม่ได้ตั้งค่าระบบตรวจอัตโนมัติ กรุณาใส่ API key ในหน้า "ตั้งค่าระบบ" ก่อน'];

    $built = ch45_ai_build_prompt($jobKey, $ctx);
    $prompt = (string)$built['prompt'];
    if (trim($prompt) === '') return ['ok' => false, 'error' => 'สร้างคำสั่งของชิ้นงานนี้ไม่ได้'];
    if (mb_strlen($prompt, 'UTF-8') > CH45_MAX_PROMPT_CHARS) {
        return ['ok' => false, 'error' => 'ข้อมูลนำเข้ายาวเกินกว่าที่จะส่งให้ระบบได้ในครั้งเดียว'];
    }

    // งาน ind_* ต้องคัดข้อความจริงและวิเคราะห์ให้ตรงจุดเป๊ะ ๆ (งานเชิงระบุตำแหน่ง/เหตุผล ไม่ใช่งานเชิงสร้างสรรค์)
    // ลดอุณหภูมิลงจากค่าปกติของทั้งระบบ (0.4) เพื่อลดโอกาสที่ระบบจะ "เดา" หรือหยิบตัวอย่างที่ไม่ตรงประเด็น
    $opts = (strpos($jobKey, 'ind_') === 0) ? ['temperature' => 0.15] : [];
    $res = ai_call_model($settings, ch45_ai_system_prompt(), $prompt, $opts);
    ai_log_usage($pdo, (string)($who['id'] ?? ''), (string)($who['role'] ?? ''), null, 'ch45:' . $jobKey,
                 $res['ok'] ? 1 : 0, $res['ok'] ? '' : (string)$res['error']);
    if (!$res['ok']) return ['ok' => false, 'error' => (string)$res['error']];

    $parsed = ch45_ai_parse($jobKey, $res['text'], $ctx, $built['evidence']);
    if ($parsed['error'] !== '') return ['ok' => false, 'error' => $parsed['error'], 'raw' => $res['text']];

    ch45_save_result($pdo, $jobKey, $parsed['payload'], [
        'raw'        => (string)$res['text'],
        'provider'   => (string)$settings['provider'],
        'model'      => (string)$settings['model'],
        'by'         => (string)($who['id'] ?? ''),
        'input_hash' => ch45_input_hash($ctx['ds'], $ctx['quant'], $ctx['defects']),
        'warnings'   => $parsed['warnings'],
    ]);

    return ['ok' => true, 'error' => '', 'payload' => $parsed['payload'],
            'warnings' => $parsed['warnings'],
            'provider' => $settings['provider'], 'model' => $settings['model']];
}

/** เตรียมข้อมูลนำเข้าทั้งหมดที่ทุกชิ้นงานใช้ร่วมกัน (เรียกครั้งเดียวต่อการวิเคราะห์หนึ่งรอบ) */
function ch45_build_context(PDO $pdo, array $opt = []) {
    $ds = ch45_dataset($pdo, $opt);

    // ความเที่ยงระหว่างผู้ประเมิน (ICC) มีอยู่แค่ในกลุ่มทดลองเท่านั้น จึงต้องดึงข้อมูลกลุ่มนี้มาคำนวณ
    // เสมอ แยกจาก $ds ที่กรองตามกลุ่มที่ผู้ใช้กำลังเลือกดูอยู่บนหน้าจอ (ปกติคือกลุ่มตัวอย่าง) —
    // ไม่เช่นนั้นตาราง 12 จะแสดงว่า "ยังไม่มีข้อมูล" เมื่อผู้ใช้ไม่ได้สลับมาดูกลุ่มทดลองอยู่
    $iccDs = (($opt['group'] ?? '') === CH45_ICC_GROUP)
        ? $ds
        : ch45_dataset($pdo, array_merge($opt, ['group' => CH45_ICC_GROUP, 'classroom' => '']));

    $quant   = ch45_quant($ds, $iccDs);
    $defects = ch45_defects($ds);
    $mech    = ch45_mechanics($pdo, $ds);
    return [
        'ds' => $ds, 'quant' => $quant, 'defects' => $defects, 'mech' => $mech,
        'results' => ch45_assign_example_numbers(ch45_results($pdo)),
        'readiness' => ch45_readiness($ds, $quant, $defects, $mech),
    ];
}

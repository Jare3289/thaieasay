/**
 * เพดานจำนวน "คู่ตัวอย่าง" ที่สมเหตุสมผลสำหรับตัวบ่งชี้หนึ่ง คำนวณจากจำนวนนักเรียนที่ปรากฏ
 * ข้อบกพร่องนี้จริงในระบบ (แถวของตาราง 14) ไม่ใช่คำนวณจากจำนวนตัวอย่างที่ระบบเผื่อหาไว้ให้เลือก
 * ตัวบ่งชี้ที่มีคนเพียง 1-2 คนไม่ควรถูกยกเป็น 2-3 คู่ เพราะฐานที่จะเลือกมีน้อยอยู่แล้ว
 * การพยายามยกหลายคู่จากกลุ่มเล็ก ๆ จะดูเหมือนพยายามยัดให้ครบมากกว่าเป็นตัวแทนของกลุ่มจริง
 * ในทางกลับกัน ตัวบ่งชี้ที่มีคนจำนวนมากควรยกได้หลายคู่เพื่อแสดงความหลากหลายของกลุ่มนั้น
 * ใช้ทั้งตอนสร้างคำสั่ง (กำหนดเพดานให้ระบบ) และตอนตรวจคำตอบ (กันไว้อีกชั้นเผื่อระบบไม่ทำตาม)
 */
function ch45_ai_suggest_pair_count(array $row) {
    $n1 = (int)($row['n1'] ?? 0);
    $n2 = (int)($row['n2'] ?? 0);
    // ไม่มีนักเรียนคนใดปรากฏข้อบกพร่องนี้เลยทั้งสองครั้ง — ไม่มีอะไรจริงให้ยกเป็นตัวอย่างเปรียบเทียบ
    // (เอา 0 คนไปเทียบกับ 0 คนไม่มีความหมายอะไรให้เขียน)
    if ($n1 === 0 && $n2 === 0) return 0;
    $base = max($n1, $n2);
    if ($base <= 2) return 1;
    if ($base <= 5) return 2;
    return 3;
}

/**
 * สร้างคำสั่ง (user prompt) ของชิ้นงานหนึ่ง
 * $ctx = ['ds' => ..., 'quant' => ..., 'defects' => ..., 'mech' => ..., 'results' => ผลของชิ้นงานก่อนหน้า]
 * คืน ['prompt' => ข้อความคำสั่ง, 'evidence' => คลังผลงานที่ใช้ (ไว้ตรวจสอบข้อความที่ระบบยกมา)]
 */
function ch45_ai_build_prompt($jobKey, array $ctx) {
    $ds      = $ctx['ds'];
    $quant   = $ctx['quant'];
    $defects = $ctx['defects'];
    $mech    = $ctx['mech'];
    $results = $ctx['results'] ?? [];
    $meta    = $ds['meta'];
    $head    = ch45_ai_context_header($ds, $quant, $defects);
    $evidence = null;

    // ---------- บทที่ 4 ตอนที่ 1 ----------
    if ($jobKey === 'quant_narrative') {
        $prompt = $head . ch45_ai_quant_block($quant) . implode("\n", [
            '=== สิ่งที่ต้องเขียน ===',
            'เขียนความเรียงภาษาไทยเชิงวิชาการสำหรับ "บทที่ 4 ตอนที่ 1" จำนวน 5 ย่อหน้า ตามหน้าที่ต่อไปนี้',
            'ย่อหน้าทั้งห้าต้องอ่านต่อกันได้เป็นเรื่องเดียว คือ เกริ่นวิธีตรวจสอบ → อ่านผลจากตาราง → ปิดท้ายด้วยข้อสรุปของตอน',
            '',
            '1. para_method — ย่อหน้าก่อนตาราง 12 ระบุว่าก่อนวิเคราะห์ผู้วิจัยตรวจสอบการแจกแจงของคะแนนผลต่าง',
            '   ด้วยวิธีของแชปิโร-วิลค์ (Shapiro-Wilk) ได้ค่า W และ p เท่าใด แปลผลว่าอย่างไร',
            '   และระบุว่าผลงานได้รับการตรวจโดยผู้ประเมิน 2 คน มีค่าสหสัมพันธ์ระหว่างผู้ประเมินเท่าใด',
            '   จึงใช้คะแนนเฉลี่ยจากผู้ประเมินทั้งสองคนในการวิเคราะห์',
            '',
            '2. para_overall — ย่อหน้าอ่านผลภาพรวมจากตาราง 12 ระบุคะแนนเฉลี่ยหลังเรียนและก่อนเรียนพร้อม SD',
            '   แล้วสรุปว่าคะแนนหลังเรียนสูงกว่าก่อนเรียนอย่างมีนัยสำคัญทางสถิติที่ระดับ .05 หรือไม่',
            '',
            '3. para_domains — ย่อหน้าไล่คะแนนเฉลี่ยรายด้านทั้ง 4 ด้าน ตามลำดับด้านที่ 1 ถึงด้านที่ 4',
            '   ระบุคะแนนเต็ม คะแนนเฉลี่ยหลังเรียนพร้อม SD และคะแนนเฉลี่ยก่อนเรียนพร้อม SD ของทุกด้าน',
            '   แล้วปิดท้ายด้วยข้อสรุปว่าทุกองค์ประกอบสูงขึ้นอย่างมีนัยสำคัญหรือไม่',
            '',
            '4. para_ranking — ย่อหน้าเปรียบเทียบขนาดของการเปลี่ยนแปลงระหว่างองค์ประกอบ',
            '   ต้องอธิบายก่อนว่าเนื่องจากคะแนนเต็มของแต่ละองค์ประกอบไม่เท่ากัน',
            '   จึงพิจารณาจากร้อยละของคะแนนเต็มร่วมกับค่าขนาดอิทธิพล',
            '   แล้วไล่ด้านที่เปลี่ยนแปลงมากที่สุดไปหาน้อยที่สุดตามลำดับที่ให้ไว้',
            '',
            '5. para_closing — ย่อหน้าสรุปปิดตอนที่ 1 ความยาว 2-4 ประโยค',
            '   ขึ้นต้นทำนองว่า "จากผลการวิเคราะห์ในตอนที่ 1 สรุปได้ว่า ..." สรุปเฉพาะสาระสำคัญของตอนนี้',
            '   (ผลการเปรียบเทียบก่อน–หลังเรียนในภาพรวมและรายด้าน) โดยไม่ต้องไล่ตัวเลขซ้ำทั้งหมด',
            '   แล้วปิดท้ายด้วยประโยคเชื่อมเข้าสู่ตอนที่ 2 ว่าผู้วิจัยจะนำเสนอผลการวิเคราะห์',
            '   การเปลี่ยนแปลงความสามารถในการเขียนเรียงความระหว่างเรียนเป็นลำดับต่อไป',
            '',
            'ตอบเป็น JSON รูปแบบนี้เท่านั้น:',
            '{"para_method":"...","para_overall":"...","para_domains":"...","para_ranking":"...","para_closing":"..."}',
        ]);
        return ['prompt' => $prompt, 'evidence' => null];
    }

    // ---------- บทที่ 4 ตอนที่ 2 รายตัวบ่งชี้ ----------
    if (strpos($jobKey, 'ind_') === 0) {
        $id  = str_replace('_', '.', substr($jobKey, 4));
        $ind = ch45_indicators()[$id] ?? null;
        if (!$ind) return ['prompt' => '', 'evidence' => null];
        $row = $defects['rows'][$id];
        $maxPairs = ch45_ai_suggest_pair_count($row);

        // รวมหมายเลขนักเรียนที่ถูกยกเป็นตัวอย่างในหัวข้ออื่นไปแล้ว (จากผลวิเคราะห์ที่มีอยู่ก่อนหน้า)
        // เพื่อให้ ch45_evidence() หลีกเลี่ยงการยกตัวอย่างคนเดิมซ้ำทุกหัวข้อเมื่อยังมีทางเลือกอื่น
        $usedW1 = []; $usedW2 = [];
        foreach ($results as $rk => $rv) {
            if (strpos($rk, 'ind_') !== 0 || $rk === $jobKey) continue;
            $pl = $rv['payload'] ?? [];
            foreach ((is_array($pl['pairs'] ?? null) ? $pl['pairs'] : []) as $pair) {
                $n1 = (int)($pair['excerpt1']['student_no'] ?? 0);
                $n2 = (int)($pair['excerpt2']['student_no'] ?? 0);
                if ($n1 > 0) $usedW1[] = $n1;
                if ($n2 > 0) $usedW2[] = $n2;
            }
        }
        // เผื่อตัวเลือกให้ระบบมากกว่าเพดานคู่จริงอีก 1 คน (กันกรณีตัวเลือกอันดับแรกเนื้อหาไม่พอยกตัวอย่าง)
        // แต่ไม่เผื่อไว้ที่ 3 เสมอเหมือนเดิม เพราะยิ่งเห็นตัวเลือกเยอะเกินจำเป็น ยิ่งมีแนวโน้มอยากยกให้ครบทุกคนที่เห็น
        $evidence = ch45_evidence($ds, $id, $defects, min(3, $maxPairs + 1), $usedW1, $usedW2);

        $extra = [];
        if ($id === '4.1') {
            $extra[] = 'ข้อมูลการสะกดคำที่นับจากตัวบทจริง: ครั้งที่ 1 พบข้อผิดพลาดเฉลี่ย '
                . ch45_fmt($mech['work1']['spell_mean']) . ' แห่งต่อผลงานหนึ่งชิ้น ครั้งที่ 2 พบเฉลี่ย '

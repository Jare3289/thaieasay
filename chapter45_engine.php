    $label = ch45_clean($label, 190);

    $L = ['=== ข้อความจากงานวิจัยที่ผู้วิจัยนำมาให้ (ต้นฉบับเดียวที่ใช้ได้) ==='];
    if ($label !== '') $L[] = 'งานชิ้นนี้คือ ' . $label;
    $L[] = $src;
    $L[] = '';


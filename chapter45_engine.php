/** ทำความสะอาดข้อความที่ระบบส่งกลับมา */
function ch45_clean($v, $maxLen = 4000) {
    if (is_array($v)) $v = implode(' ', array_map('strval', $v));
    $s = trim(preg_replace('/\s+/u', ' ', (string)$v));
    $s = str_replace(['```', '**'], '', $s);
    if (mb_strlen($s, 'UTF-8') > $maxLen) $s = mb_substr($s, 0, $maxLen, 'UTF-8');
    return $s;
}

/** ตัดช่องว่างและอักขระคั่นออกให้หมด เพื่อเทียบว่าข้อความสองก้อน "เป็นข้อความเดียวกัน" หรือไม่ */
function ch45_normalize_for_match($s) {
    $s = (string)$s;
    $s = preg_replace('/\s+/u', '', $s);
    $s = str_replace(['"', '"', '"', "'", '’', '‘', '…', '.', '/'], '', $s);
    return $s;
}

/**
 * ตรวจว่าข้อความที่ระบบยกมาเป็น "ข้อความจริง" จากผลงานของนักเรียนคนนั้นหรือไม่
 * นี่คือด่านสุดท้ายที่กันไม่ให้ตัวอย่างในบทที่ 4 เป็นข้อความที่ระบบแต่งขึ้น
 *
 * คืนค่า 'student_name' เพิ่มมาด้วย (นอกเหนือจาก 'student_no" ที่ใช้อ้างในบทที่ 4) —
 * ใช้เฉพาะตอนครู/ผู้เชี่ยวชาญเปิดโหมด "แสดงชื่อจริง" บนหน้าจอ/หน้าพิมพ์ เพื่อไล่หาต้นฉบับ
 * เท่านั้น ไม่มีผลต่อข้อความที่เขียนลงบทที่ 4 จริงซึ่งยังคงอ้างด้วยหมายเลขเสมอ
 */
function ch45_verify_excerpt(array $excerpt, array $pool) {
    $no   = (int)($excerpt['student_no'] ?? 0);
    $text = ch45_clean($excerpt['text'] ?? '', 1500);
    if ($text === '') return ['student_no' => 0, 'student_name' => '', 'text' => '', 'verified' => null, 'reason' => 'ไม่ได้ยกตัวอย่าง'];

    $needle = ch45_normalize_for_match($text);
    if ($needle === '') return ['student_no' => $no, 'student_name' => '', 'text' => $text, 'verified' => false,
                                'reason' => 'ข้อความสั้นเกินกว่าจะตรวจสอบได้'];

    // 1) ตรวจกับผลงานของนักเรียนหมายเลขที่ระบบอ้างถึงก่อน
    $owner = null;
    foreach ($pool as $c) if ((int)$c['no'] === $no) { $owner = $c; break; }
    if ($owner && mb_strpos(ch45_normalize_for_match($owner['text']), $needle, 0, 'UTF-8') !== false) {
        return ['student_no' => $no, 'student_name' => $owner['name'] ?? '', 'text' => $text, 'verified' => true, 'reason' => ''];
    }

    // 2) ถ้าไม่ตรง ลองหาว่าข้อความนี้เป็นของนักเรียนคนอื่นในคลังหรือไม่ (ระบบอ้างเลขผิด)
    foreach ($pool as $c) {
        if (mb_strpos(ch45_normalize_for_match($c['text']), $needle, 0, 'UTF-8') !== false) {
            return ['student_no' => (int)$c['no'], 'student_name' => $c['name'] ?? '', 'text' => $text, 'verified' => true,
                    'reason' => 'ระบบแก้หมายเลขนักเรียนจาก ' . $no . ' เป็น ' . $c['no'] . ' ให้ตรงกับผลงานจริง'];
        }
    }

    return ['student_no' => $no, 'student_name' => $owner['name'] ?? '', 'text' => $text, 'verified' => false,
            'reason' => 'ไม่พบข้อความนี้ในผลงานจริงที่ส่งให้ระบบ — ต้องตรวจสอบก่อนนำไปใช้'];
}

/**
 * ตรวจแบบหยาบว่าในเนื้อความย่อหน้าอภิปรายผลมี "ร่องรอยการอ้างอิงงานวิจัย" (ชื่อผู้แต่ง + ปี)
 * ที่ไม่ตรงกับ citation_used ที่แจ้งไว้และไม่มีอยู่ในคลังอ้างอิงหรือไม่ — เป็นด่านป้องกันชั้นที่สอง
 * กันกรณีระบบแอบใส่ชื่อผู้แต่งที่แต่งขึ้นเองปนอยู่ในเนื้อความ ทั้งที่ citation_used ตอบถูกต้องหรือเว้นว่างไว้
 * (เป็นการตรวจแบบ heuristic ไม่ใช่การยืนยัน 100% — ใช้ regex จับรูปแบบการอ้างอิงที่พบทั่วไปเท่านั้น)
 */
function ch45_detect_uncited_citation($text, $citeRaw, array $refs) {
    $hits = [];
    // รูปแบบ "(ชื่อผู้แต่ง, ปี)" — วงเล็บครอบทั้งชื่อและปี
    if (preg_match_all('/\(([^()]{2,60}?,\s*(?:19|20|25)\d{2})\)/u', $text, $m1)) {
        $hits = array_merge($hits, $m1[1]);
    }
    // รูปแบบ "ชื่อผู้แต่ง (ปี)" — จับเฉพาะคำสุดท้ายก่อนวงเล็บปี (ภาษาไทยไม่เว้นวรรคระหว่างคำในประโยค
    // จึงจับได้แค่ส่วนท้ายของชื่อ แต่พอสำหรับเทียบว่าเป็นส่วนหนึ่งของป้ายอ้างอิงในคลังหรือไม่)
    if (preg_match_all('/([ก-๙A-Za-z]{2,30})\s*\((?:19|20|25)\d{2}\)/u', $text, $m2)) {
        $hits = array_merge($hits, $m2[1]);
    }
    if (!$hits) return false;

    $known = [];
    foreach ($refs as $r) $known[] = ch45_normalize_for_match($r['citation_label']);
    $citeNorm = ch45_normalize_for_match($citeRaw);

    foreach ($hits as $hit) {
        $hn = ch45_normalize_for_match($hit);
        if ($hn === '' || mb_strlen($hn, 'UTF-8') < 3) continue;
        if ($citeNorm !== '' && (mb_strpos($citeNorm, $hn) !== false || mb_strpos($hn, $citeNorm) !== false)) continue;
        $foundInBank = false;
        foreach ($known as $kn) {
            if ($kn !== '' && (mb_strpos($kn, $hn) !== false || mb_strpos($hn, $kn) !== false)) { $foundInBank = true; break; }
        }
        if (!$foundInBank) return true;
    }
    return false;
}

/**
 * แปลงคำตอบดิบของระบบเป็นโครงสร้างที่ระบบใช้ต่อได้ พร้อมรายการคำเตือน
 * คืน ['payload' => ..., 'warnings' => [...], 'error' => '']
 */
function ch45_ai_parse($jobKey, $rawText, array $ctx = [], $evidence = null) {
    $obj = ai_extract_json($rawText);
    if (!is_array($obj)) {
        return ['payload' => [], 'warnings' => [], 'error' => 'คำตอบของระบบไม่ใช่รูปแบบ JSON ที่อ่านได้'];
    }
    $warn = [];

    if ($jobKey === 'quant_narrative') {
        $p = [];
        foreach (['para_method', 'para_overall', 'para_domains', 'para_ranking', 'para_closing'] as $k) {
            $p[$k] = ch45_clean($obj[$k] ?? '', 3000);
            if ($p[$k] === '') $warn[] = 'ระบบไม่ได้เขียนย่อหน้า ' . $k;
        }
        return ['payload' => $p, 'warnings' => $warn, 'error' => ''];
    }

    if (strpos($jobKey, 'ind_') === 0) {
        $id  = str_replace('_', '.', substr($jobKey, 4));
        $ind = ch45_indicators()[$id] ?? [];
        $p = [
            'indicator' => $id,
            'cell1'     => ch45_clean($obj['cell1'] ?? '', 800),
            'cell2'     => ch45_clean($obj['cell2'] ?? '', 800),
            'finding'   => ch45_clean($obj['finding'] ?? '', 2000),
            'analysis1' => ch45_clean($obj['analysis1'] ?? '', 2000),
            'analysis2' => ch45_clean($obj['analysis2'] ?? '', 2000),
            'synthesis' => ch45_clean($obj['synthesis'] ?? '', 2000),
            'caution'   => ch45_clean($obj['caution'] ?? '', 1200),
            'ex_no'     => $ind['ex'] ?? [0, 0],
        ];
        $e1 = is_array($obj['excerpt1'] ?? null) ? $obj['excerpt1'] : ['student_no' => 0, 'text' => ''];
        $e2 = is_array($obj['excerpt2'] ?? null) ? $obj['excerpt2'] : ['student_no' => 0, 'text' => ''];
        $p['excerpt1'] = ch45_verify_excerpt($e1, $evidence['work1'] ?? []);
        $p['excerpt2'] = ch45_verify_excerpt($e2, $evidence['work2'] ?? []);

        foreach (['excerpt1' => 'ตัวอย่างของผลงานครั้งที่ 1', 'excerpt2' => 'ตัวอย่างของผลงานครั้งที่ 2'] as $k => $lab) {
            if ($p[$k]['verified'] === false) $warn[] = $lab . ': ' . $p[$k]['reason'];
            if ($p[$k]['verified'] === null && $id !== '4.3') $warn[] = $lab . ': ระบบไม่ได้ยกข้อความจากผลงานจริง';
            if (!empty($p[$k]['reason']) && $p[$k]['verified'] === true) $warn[] = $lab . ': ' . $p[$k]['reason'];
        }
        if (!empty($ind['genre_bound']) && $p['caution'] === '') {
            $warn[] = 'ตัวบ่งชี้นี้ผูกกับประเภทของงานเขียนแต่ระบบไม่ได้เขียนข้อความกำกับการตีความ';
        }
        if ($p['finding'] === '') $warn[] = 'ระบบไม่ได้เขียนย่อหน้าเปิดหัวข้อ';
        return ['payload' => $p, 'warnings' => $warn, 'error' => ''];
    }

    if (strpos($jobKey, 'domain_') === 0) {
        $dk = substr($jobKey, 7);
        $d  = ch45_domains()[$dk] ?? ['indicators' => []];
        $rows = [];
        $given = is_array($obj['table_rows'] ?? null) ? $obj['table_rows'] : [];
        $byId = [];
        foreach ($given as $r) {
            if (!is_array($r)) continue;
            $byId[(string)($r['indicator'] ?? '')] = $r;
        }
        foreach ($d['indicators'] as $id) {
            $r = $byId[$id] ?? [];
            $rows[] = [
                'indicator' => $id,
                'name'      => ch45_indicators()[$id]['name'] ?? $id,
                'cell1'     => ch45_clean($r['cell1'] ?? '', 800),
                'cell2'     => ch45_clean($r['cell2'] ?? '', 800),
            ];
            if (trim((string)($r['cell1'] ?? '')) === '') $warn[] = 'ยังไม่มีข้อความในช่องตารางของตัวบ่งชี้ ' . $id;
        }
        $p = ['domain'  => $dk,
              'finding' => ch45_clean($obj['finding'] ?? '', 2000),
              'table_rows' => $rows,
              'closing' => ch45_clean($obj['closing'] ?? '', 2500)];
        if ($p['finding'] === '') $warn[] = 'ระบบไม่ได้เขียนประโยคสรุปข้อค้นพบของด้านนี้';
        if ($p['closing'] === '') $warn[] = 'ระบบไม่ได้เขียนย่อหน้าสรุปปิดด้านนี้ ก่อนขึ้นองค์ประกอบถัดไป';
        return ['payload' => $p, 'warnings' => $warn, 'error' => ''];
    }

    if ($jobKey === 'overview') {
        $cells = [];
        $src = is_array($obj['cells'] ?? null) ? $obj['cells'] : [];
        foreach (ch45_domains() as $dk => $d) {
            $c = is_array($src[$dk] ?? null) ? $src[$dk] : [];
            $cells[$dk] = [
                'name'  => $d['name'],
                'work1' => ch45_clean($c['work1'] ?? '', 1500),
                'work2' => ch45_clean($c['work2'] ?? '', 1500),
            ];
            if ($cells[$dk]['work1'] === '' || $cells[$dk]['work2'] === '') {
                $warn[] = 'ตาราง 13 ยังมีช่องว่างในด้าน' . $d['name'];
            }
        }
        $closing = ch45_clean($obj['closing'] ?? '', 3000);
        if ($closing === '') $warn[] = 'ระบบไม่ได้เขียนย่อหน้าสรุปปิดบทที่ 4';
        return ['payload' => [
            'intro'      => ch45_clean($obj['intro'] ?? '', 3000),
            'genre_note' => ch45_clean($obj['genre_note'] ?? '', 3000),
            'cells'      => $cells,
            'closing'    => $closing,
        ], 'warnings' => $warn, 'error' => ''];
    }

    if ($jobKey === 'defect_narrative') {
        $p = ['para' => ch45_clean($obj['para'] ?? '', 3000)];
        if ($p['para'] === '') $warn[] = 'ระบบไม่ได้เขียนย่อหน้าใต้ตาราง 14';
        return ['payload' => $p, 'warnings' => $warn, 'error' => ''];
    }

    if ($jobKey === 'ch5_summary') {
        $keys = ['opening', 'part1', 'part2_intro', 'part2_d1', 'part2_d2', 'part2_d3', 'part2_d4', 'part2_closing'];
        $p = [];
        foreach ($keys as $k) {
            $p[$k] = ch45_clean($obj[$k] ?? '', 3500);
            if ($p[$k] === '') $warn[] = 'ยังไม่มีเนื้อหาส่วน ' . $k;
        }
        return ['payload' => $p, 'warnings' => $warn, 'error' => ''];
    }

    if ($jobKey === 'ch5_discussion') {
        $refs = $ctx['ds']['references'] ?? [];
        $refByLabel = [];
        foreach ($refs as $r) $refByLabel[ch45_normalize_for_match($r['citation_label'])] = $r['citation_label'];

        $points = [];
        foreach ((is_array($obj['points'] ?? null) ? $obj['points'] : []) as $pt) {
            if (!is_array($pt)) continue;
            $text = ch45_clean($pt['text'] ?? '', 3000);
            if ($text === '') continue;
            $citeRaw = ch45_clean($pt['citation_used'] ?? '', 190);

            $citation = ['label' => $citeRaw, 'verified' => null, 'reason' => ''];
            if ($citeRaw !== '') {
                $norm = ch45_normalize_for_match($citeRaw);
                if (isset($refByLabel[$norm])) {
                    $citation['verified'] = true;
                    $citation['label'] = $refByLabel[$norm];
                } else {
                    $citation['verified'] = false;
                    $citation['reason'] = 'ไม่พบป้ายอ้างอิงนี้ในคลังอ้างอิงที่กรอกไว้ — ห้ามใช้จนกว่าจะตรวจสอบว่ามีอยู่จริง';
                }
            }

            $points[] = [
                'finding_key' => ch45_clean($pt['finding_key'] ?? '', 60),
                'heading'     => ch45_clean($pt['heading'] ?? '', 300),
                'text'        => $text,
                'citation'    => $citation,
                'suspect_citation' => ch45_detect_uncited_citation($text, $citeRaw, $refs),
            ];
        }

        if (!$points) $warn[] = 'ระบบยังไม่ได้เขียนประเด็นอภิปรายผลใด ๆ';
        foreach ($points as $p) {
            if ($p['citation']['verified'] === false) {
                $warn[] = 'ประเด็น "' . $p['heading'] . '" อ้างอิง "' . $p['citation']['label'] . '" ' . $p['citation']['reason'];
            }
            if ($p['suspect_citation']) {
                $warn[] = 'ประเด็น "' . $p['heading'] . '" มีข้อความคล้ายการอ้างอิงงานวิจัยอื่นปะปนอยู่ในเนื้อหาที่ไม่ได้แจ้งไว้ '
                        . 'ต้องตรวจสอบว่าเป็นการอ้างอิงจริงหรือระบบแต่งขึ้นเอง ก่อนนำไปใช้';
            }
        }
        $closing = ch45_clean($obj['closing'] ?? '', 3000);
        if ($points && $closing === '') $warn[] = 'ระบบไม่ได้เขียนย่อหน้าสรุปปิดการอภิปรายผล ก่อนขึ้นข้อเสนอแนะ';
        return ['payload' => ['points' => $points, 'closing' => $closing], 'warnings' => $warn, 'error' => ''];
    }

    if ($jobKey === 'ch5_recommend') {
        $items = [];
        foreach ((is_array($obj['items'] ?? null) ? $obj['items'] : []) as $i) {
            if (!is_array($i)) continue;
            $t = ch45_clean($i['text'] ?? '', 2500);
            if ($t === '') continue;
            $items[] = ['stage' => ch45_clean($i['stage'] ?? '', 120), 'text' => $t];
        }
        $future = [];
        foreach ((is_array($obj['future'] ?? null) ? $obj['future'] : []) as $f) {
            $t = is_array($f) ? ch45_clean($f['text'] ?? '', 2000) : ch45_clean($f, 2000);
            if ($t !== '') $future[] = ['text' => $t];
        }
        if (!$items) $warn[] = 'ยังไม่มีข้อเสนอแนะ — ต้องบันทึก "บันทึกหลังสอน" ในระบบก่อน เพราะข้อเสนอแนะส่วนนี้ต้องมาจากปัญหาที่พบจริง';
        return ['payload' => ['items' => $items,
                              'institution' => ch45_clean($obj['institution'] ?? '', 2500),
                              'future' => $future,
                              'closing' => ch45_clean($obj['closing'] ?? '', 2000),
                              'note' => ch45_clean($obj['note'] ?? '', 1500)],
                'warnings' => $warn, 'error' => ''];
    }

    return ['payload' => [], 'warnings' => [], 'error' => 'ไม่รู้จักชิ้นงาน ' . $jobKey];
}


function ai_quality_level($total60) {
    if ($total60 >= 49) return 'ดีมาก';
    if ($total60 >= 37) return 'ดี';
    if ($total60 >= 25) return 'ปานกลาง';
    if ($total60 >= 13) return 'พอใช้';
    return 'ต้องปรับปรุง';
}


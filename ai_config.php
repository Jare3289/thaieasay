    } catch (Exception $e) { /* บันทึกไม่ได้ไม่ควรทำให้ฟีเจอร์หลักพัง */ }
}

/** แปลงแถวในตาราง essay_ai_feedback ให้เป็นโครงสร้างที่หน้าเว็บใช้ได้ทันที */
function ai_feedback_row_to_array(array $row, ?array $evalManual = null, ?array $essayParts = null) {
    $decode = function ($v) {
        $d = json_decode((string)$v, true);
        return is_array($d) ? $d : [];
    };
    $out = [
        'student_id'    => $row['student_id'],
        'student_name'  => isset($row['student_name']) ? formatNamePrefix($row['student_name']) : '',
        'classroom'     => $row['classroom'] ?? '',
        'essay_phase'   => $row['essay_phase'],
        'phase_label'   => ai_phase_label($row['essay_phase']),
        'overall'       => (string)$row['overall_comment'],
        'strengths'     => $decode($row['strengths']),
        'improvements'  => $decode($row['improvements']),
        'next_steps'    => $decode($row['next_steps']),
        'encouragement' => (string)$row['encouragement'],
        'scores'        => $decode($row['scores']),
        'total_score'   => (float)$row['total_score'],
        'max_score'     => (float)$row['max_score'],
        'quality_level' => (string)$row['quality_level'],
        // ผลตรวจที่ไม่มีคะแนนเลย = การตรวจครั้งนั้นไม่ผ่าน (ข้อมูลเก่าที่บันทึกไว้ก่อนระบบจะปฏิเสธผลไม่สมบูรณ์)
        // ถือว่ายังไม่ได้ตรวจ ต้องสั่งตรวจใหม่ ไม่ควรนำคะแนนไปใช้
        'incomplete'    => empty($decode($row['scores'])),
        'model'         => (string)$row['model'],
        'provider'      => (string)$row['provider'],
        'requested_by'  => (string)$row['requested_by'],
        'requested_role'=> (string)$row['requested_role'],
        'created_at'    => (string)$row['created_at'],
        'updated_at'    => (string)($row['updated_at'] ?? ''),
        // ต้นฉบับถูกแก้ไขหลัง AI ตรวจหรือยัง (ใช้แสดงป้าย "รอตรวจใหม่" และจัดคิวตรวจซ้ำ)
        'needs_recheck'     => !empty($row['recheck_needed']),
        'recheck_marked_at' => (string)($row['recheck_marked_at'] ?? ''),
        // ตรวจฉบับนี้เป็นครั้งที่เท่าไร (ตัวนับเฉย ๆ — ระบบไม่ได้เทียบผลตรวจข้ามครั้งแล้ว)
        'review_round'      => max(1, (int)($row['review_round'] ?? 1)),
        // เทียบกับฉบับตั้งต้นตามคู่ที่ครูกำหนด (D1.2↔D1.1, D2.2↔D2.1, หลังเรียน↔ก่อนเรียน)
        'draft_comment'     => (string)($row['draft_comment'] ?? ''),
        'baseline_phase'    => (string)($row['baseline_phase'] ?? ''),
    ];

    // คะแนนที่ถูกปรับรายข้อ (ครูปรับเอง หรือสั่งให้ AI ตรวจเฉพาะข้อนั้นใหม่)
    // ทับลงบนคะแนนของ AI ให้กลายเป็น "คะแนนที่ใช้จริง" ก่อนคิดผลเทียบร่าง
    // ตารางเทียบร่างจะได้ใช้คะแนนชุดเดียวกับที่แสดงในตารางคะแนนรายเกณฑ์
    $out = ai_apply_score_overrides($out, $row['score_overrides'] ?? '');

    // เทียบกับ "ฉบับตั้งต้น" คนละฉบับ (ร่างที่ 1 ของหน่วยเดียวกัน หรือฉบับก่อนเรียน)
    // คอลัมน์ draft_changes เก็บเป็น {criteria, edits} — ข้อมูลเก่าที่เก็บเป็นอาเรย์ล้วนก็ยังอ่านได้
    $dcRaw  = $decode($row['draft_changes'] ?? '');
    $dcCrit = (isset($dcRaw['criteria']) && is_array($dcRaw['criteria'])) ? $dcRaw['criteria'] : $dcRaw;
    $dcEdit = (isset($dcRaw['edits']) && is_array($dcRaw['edits'])) ? $dcRaw['edits'] : [];
    $out['draft_changes'] = $dcCrit;

    // ผลตรวจที่บันทึกไว้ก่อนระบบจะเก็บ "ส่วนที่แก้" ให้ (หรือฐานข้อมูลเก่าที่ยังไม่มีคอลัมน์)
    // ยังบอกได้ว่าแก้อะไรไปตรงไหน โดยเทียบข้อความของสองฉบับสด ๆ ตอนเปิดดู
    // ผู้เรียกส่ง $essayParts มาเป็น [รหัสรอบงาน => ผลของ ai_essay_parts()] ถ้ามีข้อความให้เทียบ
    // คู่คนละหัวข้อ (ก่อนเรียน↔หลังเรียน) ไม่ต้องเทียบข้อความ เพราะเป็นงานเขียนคนละชิ้น
    $editsLive = false;
    if (!$dcEdit && $essayParts !== null && ai_baseline_kind($row['essay_phase']) !== 'newtopic') {
        $basePh = ai_baseline_phase($row['essay_phase']);
        if ($basePh !== '' && !empty($essayParts[$basePh]) && !empty($essayParts[$row['essay_phase']])) {
            $dcEdit    = ai_diff_essay_parts($essayParts[$basePh], $essayParts[$row['essay_phase']]);
            $editsLive = true;
        }
    }

    $out['draft_compare'] = ai_draft_progress(
        $out,
        $decode($row['baseline_snapshot'] ?? ''),
        (string)($row['essay_hash'] ?? ''),
        (int)($row['word_count'] ?? 0),
        $dcEdit,
        $editsLive
    );

    // ตัวเรียงความของทั้งสองฉบับวางคู่กันไว้ให้ครู "อ่านเทียบ" เต็ม ๆ
    // มีเฉพาะเมื่อผู้เรียกส่งข้อความของทั้งสองฉบับมาให้ (หน้าผลตรวจรายบุคคล)
    // ตารางภาพรวมทั้งชั้นไม่ต้องใช้ จึงไม่ส่งข้อความเรียงความไปให้เปลืองข้อมูล
    if ($essayParts !== null && !empty($out['draft_compare']['pairable'])) {
        $sbsBase = ai_baseline_phase($row['essay_phase']);
        if ($sbsBase !== '' && !empty($essayParts[$sbsBase]) && !empty($essayParts[$row['essay_phase']])) {
            $out['draft_compare']['side_by_side'] = ai_side_by_side_parts(
                $essayParts[$sbsBase],
                $essayParts[$row['essay_phase']],
                ai_baseline_kind($row['essay_phase']) !== 'newtopic'
            );
        }
    }

    $tScores = $decode($row['teacher_scores'] ?? '');
    $tTotal  = $row['teacher_total'] ?? 0;
    $tBy     = $row['teacher_by'] ?? '';
    $tAt     = (string)($row['teacher_scored_at'] ?? '');
    $tSource = $tScores ? 'ai_page' : '';

    // ยังไม่ได้กรอกคะแนนข้อนี้ในหน้าผู้ช่วย AI แต่คุณครูเคยให้คะแนนไว้ในแบบประเมินแล้ว
    // → ดึงคะแนนจากหน้า evaluation.php มาใช้เลย ไม่ต้องกรอกซ้ำ
    if (!$tScores && $evalManual !== null) {
        $ev = $evalManual[$row['essay_phase']] ?? null;
        if ($ev && !empty($ev['scores'])) {
            $tScores = $ev['scores'];
            $tTotal  = $ev['total'];
            $tBy     = $ev['by'];
            $tAt     = $ev['at'];
            $tSource = 'evaluation';
        }
    }

    return ai_attach_manual($out, $tScores, $tTotal, $tBy, $tAt, $tSource);
}

/** แปลงคำตอบภาพรวมรายรอบงานของ AI ให้เป็นโครงสร้างมาตรฐาน */
function ai_parse_phase_overview($rawText) {
    $obj = ai_extract_json($rawText);
    if (!is_array($obj)) {
        return ['ok' => false, 'data' => [], 'error' => 'อ่านคำตอบของ AI ไม่ได้ (ไม่ใช่ JSON ที่สมบูรณ์) กรุณาลองใหม่อีกครั้ง'];
    }

    $listOf = function ($raw, $maxLen = 600) {
        $out = [];
        if (is_array($raw)) {
            foreach ($raw as $v) {
                $t = ai_clean_text(is_array($v) ? implode(' ', $v) : $v, $maxLen);
                if ($t !== '') $out[] = $t;
            }
        }
        return $out;
    };

    $themes = [];
    if (isset($obj['themes']) && is_array($obj['themes'])) {
        foreach ($obj['themes'] as $t) {
            if (is_array($t)) {
                $item = [
                    'theme'    => ai_clean_text($t['theme'] ?? '', 300),
                    'how_many' => ai_clean_text($t['how_many'] ?? '', 60),
                    'example'  => ai_clean_text($t['example'] ?? '', 400),
                ];
                if ($item['theme'] !== '') $themes[] = $item;
            } else {
                $tt = ai_clean_text($t, 300);
                if ($tt !== '') $themes[] = ['theme' => $tt, 'how_many' => '', 'example' => ''];
            }
        }
    }

    $data = [
        'overview'         => ai_clean_text($obj['overview'] ?? '', 2000),
        'themes'           => $themes,
        'interesting'      => $listOf($obj['interesting'] ?? null),
        'common_strengths' => $listOf($obj['common_strengths'] ?? null),
        'common_problems'  => $listOf($obj['common_problems'] ?? null),
        'observations'     => $listOf($obj['observations'] ?? null, 800),
        'teaching_notes'   => $listOf($obj['teaching_notes'] ?? null),
    ];

    if ($data['overview'] === '' && !$themes && !$data['observations']) {
        return ['ok' => false, 'data' => [], 'error' => 'AI ตอบกลับมาไม่ครบถ้วน กรุณาลองใหม่อีกครั้ง'];
    }
    return ['ok' => true, 'data' => $data, 'error' => ''];
}

/**
 * ส่ง HTTP POST แบบ JSON (ใช้ cURL ถ้ามี ไม่มีก็ถอยไปใช้ stream context)
 * คืนค่า ['ok' => bool, 'status' => int, 'body' => string, 'error' => string]
 */
function ai_http_post_json($url, array $headers, array $payload, $timeout = 90) {
    $json = json_encode($payload, JSON_UNESCAPED_UNICODE);

    if (function_exists('curl_init')) {
        $ch = curl_init($url);
        curl_setopt_array($ch, [
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_POST           => true,
            CURLOPT_POSTFIELDS     => $json,
            CURLOPT_HTTPHEADER     => array_merge(['Content-Type: application/json'], $headers),
            CURLOPT_TIMEOUT        => $timeout,
            CURLOPT_CONNECTTIMEOUT => 15,
        ]);
        $body   = curl_exec($ch);
        $status = (int)curl_getinfo($ch, CURLINFO_HTTP_CODE);
        $err    = curl_error($ch);
        curl_close($ch);
        if ($body === false) {
            return ['ok' => false, 'status' => 0, 'body' => '', 'error' => 'เชื่อมต่อผู้ให้บริการ AI ไม่ได้: ' . $err];
        }
        return ['ok' => ($status >= 200 && $status < 300), 'status' => $status, 'body' => (string)$body, 'error' => ''];
    }

    // สำรอง: โฮสต์ที่ไม่ได้เปิด cURL แต่เปิด allow_url_fopen
    $ctx = stream_context_create(['http' => [
        'method'        => 'POST',
        'header'        => implode("\r\n", array_merge(['Content-Type: application/json'], $headers)),
        'content'       => $json,
        'timeout'       => $timeout,
        'ignore_errors' => true,
    ]]);
    $body = @file_get_contents($url, false, $ctx);
    if ($body === false) {
        return ['ok' => false, 'status' => 0, 'body' => '', 'error' => 'เซิร์ฟเวอร์เรียก API ภายนอกไม่ได้ (ต้องเปิด cURL หรือ allow_url_fopen)'];
    }
    $status = 0;
    if (isset($http_response_header) && is_array($http_response_header)) {
        foreach ($http_response_header as $h) {
            if (preg_match('#^HTTP/\S+\s+(\d{3})#', $h, $m)) $status = (int)$m[1];
        }
    }
    return ['ok' => ($status >= 200 && $status < 300), 'status' => $status, 'body' => (string)$body, 'error' => ''];
}

/** ดึงข้อความผิดพลาดที่อ่านรู้เรื่องออกจากคำตอบ error ของผู้ให้บริการ */
function ai_extract_api_error($body, $status) {
    $obj = json_decode((string)$body, true);
    $msg = '';
    if (is_array($obj)) {
        if (isset($obj['error']['message'])) $msg = (string)$obj['error']['message'];
        elseif (isset($obj['error']) && is_string($obj['error'])) $msg = $obj['error'];
        elseif (isset($obj['message'])) $msg = (string)$obj['message'];
    }
    if ($msg === '') $msg = mb_substr(strip_tags((string)$body), 0, 300, 'UTF-8');

    if ($status === 401 || $status === 403) {
        return 'API key ไม่ถูกต้องหรือหมดสิทธิ์ใช้งาน (' . $msg . ')';
    }
    if ($status === 429) {
        return 'ใช้โควตาฟรีของผู้ให้บริการครบแล้วในช่วงนี้ กรุณารอสักครู่แล้วลองใหม่ (' . $msg . ')';
    }
    if ($status === 404) {
        return 'ไม่พบโมเดลที่ตั้งค่าไว้ กรุณาตรวจสอบชื่อโมเดลในหน้าตั้งค่า AI (' . $msg . ')';
    }
    return 'ผู้ให้บริการ AI ตอบกลับข้อผิดพลาด (HTTP ' . $status . '): ' . $msg;
}

/**
 * เรียกโมเดล AI ให้ตอบเป็นข้อความ
 * คืนค่า ['ok' => bool, 'text' => string, 'error' => string]
 */
function ai_call_model(array $s, $systemPrompt, $userPrompt) {
    if (!$s['configured']) {
        return ['ok' => false, 'text' => '', 'finish' => '',
                'error' => 'ยังไม่ได้ตั้งค่า AI (ขาด API key หรือชื่อโมเดล) กรุณาตั้งค่าในหน้า "ผู้ช่วย AI"'];
    }

    if ($s['kind'] === 'gemini') {
        $url = $s['base_url'] . '/models/' . rawurlencode($s['model']) . ':generateContent';
        $payload = [
            'system_instruction' => ['parts' => [['text' => $systemPrompt]]],
            'contents'           => [['role' => 'user', 'parts' => [['text' => $userPrompt]]]],
            'generationConfig'   => [
                'temperature'      => 0.4,
                'responseMimeType' => 'application/json',
                // เดิมตั้งไว้ 4096 ซึ่งน้อยเกินไป: คำตอบเป็นภาษาไทย (กินโทเคนมากกว่าอังกฤษหลายเท่า)
                // และโมเดลรุ่นใหม่ยังใช้โทเคนส่วนหนึ่งไป "คิด" ก่อนตอบ พอโควตาหมดกลางคัน
                // JSON จะถูกตัดครึ่งแล้วอ่านไม่ออก ("รูปแบบไม่ใช่ JSON")
                'maxOutputTokens'  => 32768,
            ],
        ];
        $res = ai_http_post_json($url, ['x-goog-api-key: ' . $s['api_key']], $payload);
        if ($res['error'] !== '') return ['ok' => false, 'text' => '', 'error' => $res['error']];
        if (!$res['ok'])          return ['ok' => false, 'text' => '', 'error' => ai_extract_api_error($res['body'], $res['status'])];

        $obj  = json_decode($res['body'], true);
        $text = '';
        if (isset($obj['candidates'][0]['content']['parts']) && is_array($obj['candidates'][0]['content']['parts'])) {
            foreach ($obj['candidates'][0]['content']['parts'] as $part) {
                if (isset($part['text'])) $text .= $part['text'];
            }
        }
        $reason = isset($obj['candidates'][0]['finishReason']) ? (string)$obj['candidates'][0]['finishReason'] : '';
        if (trim($text) === '') {
            return ['ok' => false, 'text' => '', 'finish' => $reason,
                    'error' => 'AI ไม่ได้ส่งเนื้อหากลับมา' . ($reason !== '' ? " (สาเหตุ: $reason)" : '')];
        }
        return ['ok' => true, 'text' => $text, 'error' => '', 'finish' => $reason];
    }

    // มาตรฐาน OpenAI (typhoon / openrouter / groq / custom)
    $url  = $s['base_url'] . '/chat/completions';
    $head = ['Authorization: Bearer ' . $s['api_key']];
    if ($s['provider'] === 'openrouter') {
        // OpenRouter แนะนำให้ระบุที่มาของคำขอ
        $head[] = 'X-Title: Thai Essay Feedback';
    }
    $base = [
        'model'       => $s['model'],
        'messages'    => [
            ['role' => 'system', 'content' => $systemPrompt],
            ['role' => 'user',   'content' => $userPrompt],
        ],
        'temperature' => 0.4,
        'max_tokens'  => 8192,
    ];

    // ลองใช้โหมดบังคับ JSON ก่อน ถ้าโมเดลไม่รองรับค่อยยิงซ้ำแบบธรรมดา
    $res = ai_http_post_json($url, $head, array_merge($base, ['response_format' => ['type' => 'json_object']]));
    if ($res['error'] !== '') return ['ok' => false, 'text' => '', 'error' => $res['error']];
    if (!$res['ok'] && $res['status'] === 400) {
        $res = ai_http_post_json($url, $head, $base);
        if ($res['error'] !== '') return ['ok' => false, 'text' => '', 'error' => $res['error']];
    }
    if (!$res['ok']) return ['ok' => false, 'text' => '', 'error' => ai_extract_api_error($res['body'], $res['status'])];

    $obj  = json_decode($res['body'], true);
    $text   = isset($obj['choices'][0]['message']['content']) ? (string)$obj['choices'][0]['message']['content'] : '';
    $reason = isset($obj['choices'][0]['finish_reason']) ? (string)$obj['choices'][0]['finish_reason'] : '';
    if (trim($text) === '') return ['ok' => false, 'text' => '', 'finish' => $reason, 'error' => 'AI ไม่ได้ส่งเนื้อหากลับมา'];
    return ['ok' => true, 'text' => $text, 'error' => '', 'finish' => $reason];
}

/** ดึงก้อน JSON ออกจากข้อความที่ AI ตอบ (เผื่อมี ``` หรือคำอธิบายห่อไว้) */
function ai_extract_json($text) {
    $t = trim((string)$text);
    $t = preg_replace('/^```(?:json)?\s*/i', '', $t);
    $t = preg_replace('/\s*```$/', '', $t);
    $obj = json_decode($t, true);
    if (is_array($obj)) return $obj;

    $start = strpos($t, '{');
    $end   = strrpos($t, '}');
    if ($start !== false && $end !== false && $end > $start) {
        $obj = json_decode(substr($t, $start, $end - $start + 1), true);
        if (is_array($obj)) return $obj;
    }
    // ทางสุดท้าย: คำตอบอาจถูกตัดกลางคันเพราะชนเพดานโทเคน — ลองกู้เท่าที่มี
    return ai_salvage_json($t);
}

/**
 * กู้ JSON ที่ถูกตัดกลางคัน (เช่นโมเดลตอบยาวจนชนเพดานโทเคน)
 * วิธี: ตัดค่าที่ค้างครึ่ง ๆ ทิ้ง แล้วปิดวงเล็บที่ยังเปิดค้างอยู่ให้ครบ
 * คืน array ถ้ากู้สำเร็จ หรือ null ถ้ากู้ไม่ได้
 */
function ai_salvage_json($text) {
    $t = (string)$text;
    $start = strpos($t, '{');
    if ($start === false) return null;
    $t = substr($t, $start);

    // เดินอ่านทีละอักขระเพื่อหาว่าข้อความจบลงกลางสตริงหรือไม่
    $inStr = false; $esc = false; $strStart = -1;
    for ($i = 0, $len = strlen($t); $i < $len; $i++) {
        $c = $t[$i];
        if ($inStr) {
            if ($esc)            { $esc = false; continue; }
            if ($c === '\\')     { $esc = true;  continue; }
            if ($c === '"')      { $inStr = false; }
            continue;
        }
        if ($c === '"') { $inStr = true; $strStart = $i; }
    }
    // จบกลางสตริง → ตัดสตริงที่ค้างทิ้งทั้งตัว
    if ($inStr && $strStart >= 0) $t = substr($t, 0, $strStart);

    // เก็บกวาดเศษท้ายที่ไม่สมบูรณ์ (คอมมา, โคลอน, ชื่อคีย์ที่ยังไม่มีค่า)
    $t = rtrim($t);
    for ($pass = 0; $pass < 3; $pass++) {
        $t = preg_replace('/\s*[,:]\s*$/', '', $t);
        $t = preg_replace('/,\s*"[^"]*"\s*$/', '', $t);   // ,"key" ค้าง
        $t = preg_replace('/\{\s*"[^"]*"\s*$/', '{', $t); // {"key" ค้าง
        $t = rtrim($t);
    }

    // นับวงเล็บที่ยังเปิดค้าง (นอกสตริง) แล้วปิดให้ครบตามลำดับย้อนกลับ
    $stack = []; $inStr = false; $esc = false;
    for ($i = 0, $len = strlen($t); $i < $len; $i++) {
        $c = $t[$i];
        if ($inStr) {
            if ($esc)        { $esc = false; continue; }
            if ($c === '\\') { $esc = true;  continue; }
            if ($c === '"')  { $inStr = false; }
            continue;
        }
        if ($c === '"')                 { $inStr = true; }
        elseif ($c === '{' || $c === '[') { $stack[] = $c; }
        elseif ($c === '}' || $c === ']') { array_pop($stack); }
    }
    while (!empty($stack)) {
        $t .= (array_pop($stack) === '{') ? '}' : ']';
    }

    $obj = json_decode($t, true);
    return is_array($obj) ? $obj : null;
}

/** ทำความสะอาดข้อความจาก AI ก่อนเก็บลงฐานข้อมูล */
function ai_clean_text($v, $maxLen = 2000) {
    $s = trim(preg_replace('/\s+/u', ' ', (string)$v));
    if (mb_strlen($s, 'UTF-8') > $maxLen) $s = mb_substr($s, 0, $maxLen, 'UTF-8') . '…';
    return $s;
}

/**
 * แปลงคำตัดสินของ AI เมื่อเทียบฉบับนี้กับ "ฉบับตั้งต้น" ให้เป็นรหัสมาตรฐาน
 * 'better' = ดีขึ้น, 'worse' = แย่ลง, 'same' = เท่าเดิม, '' = AI ไม่ได้ระบุ
 */
function ai_verdict_code($v) {
    $t = mb_strtolower(trim((string)$v), 'UTF-8');
    if ($t === '') return '';
    if (mb_strpos($t, 'ดีขึ้น') !== false || mb_strpos($t, 'better') !== false
        || mb_strpos($t, 'improve') !== false || mb_strpos($t, 'up') !== false)      return 'better';
    if (mb_strpos($t, 'แย่ลง') !== false || mb_strpos($t, 'ถอย') !== false
        || mb_strpos($t, 'worse') !== false || mb_strpos($t, 'down') !== false)      return 'worse';
    if (mb_strpos($t, 'เท่าเดิม') !== false || mb_strpos($t, 'เหมือนเดิม') !== false
        || mb_strpos($t, 'ไม่ต่าง') !== false || mb_strpos($t, 'same') !== false
        || mb_strpos($t, 'unchanged') !== false)                                     return 'same';
    return '';
}

/**
 * แปลงคำตอบดิบของ AI เป็นโครงสร้างมาตรฐานของระบบ พร้อมคำนวณคะแนนถ่วงน้ำหนัก
 * คืนค่า ['ok' => bool, 'data' => array, 'error' => string]
 */
function ai_parse_feedback($rawText) {
    $obj = ai_extract_json($rawText);
    if (!is_array($obj)) {
        $peek = ai_clean_text(mb_substr(trim((string)$rawText), 0, 160, 'UTF-8'), 200);
        return ['ok' => false, 'data' => [], 'error' =>
            'อ่านคำตอบของ AI ไม่ได้ (ไม่ใช่ JSON ที่สมบูรณ์) กรุณากดตรวจใหม่อีกครั้ง'
            . ($peek !== '' ? ' — คำตอบที่ได้ขึ้นต้นว่า: "' . $peek . '"' : ' — AI ไม่ได้ส่งข้อความใด ๆ กลับมา')];
    }

    $strengths = [];
    if (isset($obj['strengths']) && is_array($obj['strengths'])) {
        foreach ($obj['strengths'] as $v) {
            $t = ai_clean_text(is_array($v) ? implode(' ', $v) : $v, 600);
            if ($t !== '') $strengths[] = $t;
        }
    }

    $improvements = [];
    if (isset($obj['improvements']) && is_array($obj['improvements'])) {
        foreach ($obj['improvements'] as $v) {
            if (is_array($v)) {
                $item = [
                    'criterion'  => ai_clean_text($v['criterion'] ?? '', 20),
                    'issue'      => ai_clean_text($v['issue'] ?? '', 800),
                    'suggestion' => ai_clean_text($v['suggestion'] ?? '', 800),
                    'example'    => ai_clean_text($v['example'] ?? '', 400),
                ];
                if ($item['issue'] !== '' || $item['suggestion'] !== '') $improvements[] = $item;
            } else {
                $t = ai_clean_text($v, 800);
                if ($t !== '') $improvements[] = ['criterion' => '', 'issue' => $t, 'suggestion' => '', 'example' => ''];
            }
        }
    }

    $listOf = function ($raw, $maxLen) {
        $out = [];
        if (is_array($raw)) {
            foreach ($raw as $v) {
                $t = ai_clean_text(is_array($v) ? implode(' ', $v) : $v, $maxLen);
                if ($t !== '') $out[] = $t;
            }
        }
        return $out;
    };
    // เทียบกับ "ฉบับตั้งต้น" คนละฉบับ (D1.2 เทียบ D1.1, D2.2 เทียบ D2.1, หลังเรียน เทียบ ก่อนเรียน)
    $draftChanges = [];
    if (isset($obj['draft_changes']) && is_array($obj['draft_changes'])) {
        foreach ($obj['draft_changes'] as $v) {
            if (!is_array($v)) continue;
            $changedRaw = mb_strtolower(trim((string)($v['changed'] ?? '')), 'UTF-8');
            $item = [
                'criterion' => ai_clean_text($v['criterion'] ?? '', 20),
                // AI บอกว่าข้อนี้มีอะไรเปลี่ยนไหม
                'changed'   => ($changedRaw === '' ? null
                                 : !in_array($changedRaw, ['no', 'false', 'ไม่', 'ไม่เปลี่ยน', 'ไม่ได้แก้'], true)),
                // สามคำถามหลักของแต่ละข้อ: อะไรเพิ่มมา อะไรหายไป และทำไมคะแนนจึงขยับ
                'added'     => ai_clean_text($v['added'] ?? '', 600),
                'removed'   => ai_clean_text($v['removed'] ?? '', 600),
                'reason'    => ai_clean_text($v['reason'] ?? '', 800),
                // รูปแบบเดิมของคำตอบ (ยังรับไว้ เผื่อโมเดลตอบมาแบบเก่า และเพื่ออ่านข้อมูลที่เก็บไว้ก่อนหน้า)
                'change'    => ai_clean_text($v['change'] ?? '', 800),
                'before'    => ai_clean_text($v['before'] ?? '', 600),
                'after'     => ai_clean_text($v['after'] ?? '', 600),
                'verdict'   => ai_verdict_code($v['verdict'] ?? ''),
                'note'      => ai_clean_text($v['note'] ?? '', 400),
            ];
            $filled = $item['added'] . $item['removed'] . $item['reason']
                    . $item['change'] . $item['before'] . $item['after'] . $item['note'];
            if ($filled !== '') $draftChanges[] = $item;
        }
    }

    $nextSteps = [];
    if (isset($obj['next_steps']) && is_array($obj['next_steps'])) {
        foreach ($obj['next_steps'] as $v) {
            $t = ai_clean_text(is_array($v) ? implode(' ', $v) : $v, 500);
            if ($t !== '') $nextSteps[] = $t;
        }
    }

    // คะแนน: รับคะแนนดิบ 0-4 ต่อข้อ แล้วคูณตัวถ่วงน้ำหนักตามเกณฑ์จริงของครู
    $rawScores = (isset($obj['scores']) && is_array($obj['scores'])) ? $obj['scores'] : [];
    $reasons   = (isset($obj['score_reasons']) && is_array($obj['score_reasons'])) ? $obj['score_reasons'] : [];
    $scores    = [];
    $total     = 0.0;
    $graded    = 0;
    foreach (ai_rubric() as $it) {
        if (!$it['ai']) continue;
        if (!array_key_exists($it['id'], $rawScores) || !is_numeric($rawScores[$it['id']])) continue;
        $raw = (float)$rawScores[$it['id']];
        if ($raw < 0) $raw = 0;
        if ($raw > 4) $raw = 4;
        $weighted = round($raw * $it['multiplier'], 2);
        $scores[$it['id']] = [
            'raw'      => $raw,
            'weighted' => $weighted,
            'max'      => $it['max'],
            'name'     => $it['name'],
            'reason'   => ai_clean_text($reasons[$it['id']] ?? '', 500),
        ];
        $total += $weighted;
        $graded++;
    }

    $maxScore = ai_rubric_max();
    $total    = round($total, 2);
    // เทียบระดับคุณภาพบนสเกลเต็ม 60 (เกณฑ์เดียวกับครู) โดยเทียบสัดส่วนจากข้อที่ AI ตรวจได้
    $scaled60 = ($maxScore > 0) ? ($total / $maxScore) * 60 : 0;

    $data = [
        'overall'       => ai_clean_text($obj['overall'] ?? ($obj['summary'] ?? ''), 2000),
        'strengths'     => $strengths,
        'improvements'  => $improvements,
        'next_steps'    => $nextSteps,
        'encouragement' => ai_clean_text($obj['encouragement'] ?? '', 600),
        // มีเฉพาะรอบที่มีฉบับตั้งต้นให้เทียบ — AI สรุปว่าฉบับนี้ต่างจากฉบับตั้งต้นอย่างไร
        'draft_comment' => ai_clean_text($obj['draft_comment'] ?? '', 1500),
        'draft_changes' => $draftChanges,
        'scores'        => $scores,
        'total_score'   => $total,
        'max_score'     => $maxScore,
        'graded_items'  => $graded,
        'quality_level' => ($graded > 0) ? ai_quality_level($scaled60) : '',
    ];

    if ($data['overall'] === '' && empty($improvements) && empty($strengths)) {
        return ['ok' => false, 'data' => [], 'error' => 'AI ตอบกลับมาไม่ครบถ้วน กรุณากดตรวจใหม่อีกครั้ง'];
    }

    // ---- ผลตรวจที่ให้คะแนนไม่ครบ ถือว่า "ตรวจไม่ผ่าน" ----
    // เดิมระบบยอมรับผลที่ AI ให้คะแนนมาไม่ครบ (หรือไม่ให้เลย) แล้วบันทึกลงฐานข้อมูล
    // ฉบับนั้นจึงถูกนับว่า "ตรวจแล้ว" ทั้งที่คะแนนขาดหรือเป็น 0 ถูกข้ามในการตรวจทั้งรอบ
    // และคะแนนที่ขาดยังทำให้สถิติของงานวิจัยเพี้ยนด้วย
    // ตอนนี้ถ้าให้คะแนนไม่ครบทุกข้อ จะไม่บันทึกอะไรเลย ฉบับนั้นยังเป็น "ยังไม่ตรวจ" และสั่งตรวจใหม่ได้
    $needIds = [];
    foreach (ai_rubric() as $it) {
        if ($it['ai']) $needIds[] = $it['id'];
    }
    $missing = array_values(array_diff($needIds, array_keys($scores)));
    if ($missing) {
        return ['ok' => false, 'data' => [], 'error' =>
            'AI ให้คะแนนมาไม่ครบทุกข้อ (ขาดข้อ ' . implode(', ', $missing) . ' จาก '
            . count($needIds) . ' ข้อ) ระบบจึงยังไม่บันทึกผล — ถือว่าฉบับนี้ยังไม่ได้ตรวจ กรุณากดตรวจใหม่อีกครั้ง'];
    }

    return ['ok' => true, 'data' => $data, 'error' => ''];
}

/* ===========================================================================
 * คะแนนที่ "ถูกปรับรายข้อ" หลัง AI ตรวจเสร็จ
 *
 * คุณครูไม่เห็นด้วยกับคะแนนที่ AI ให้ในข้อไหน ทำได้ 2 ทาง
 *   1) ปรับคะแนนข้อนั้นเอง พร้อมเขียนเหตุผลกำกับ            (source = teacher)
 *   2) สั่งให้ AI ตรวจเฉพาะข้อนั้นใหม่ ใส่คำสั่งเพิ่มเติมได้ (source = ai_recheck)
 *
 * หลักการสำคัญของงานวิจัย: ไม่ทับคะแนนเดิมของ AI เด็ดขาด
 * คอลัมน์ scores ยังเป็นคะแนนที่ AI ให้ครั้งแรกเสมอ ส่วนคะแนนที่ปรับเก็บแยกไว้ใน
 * คอลัมน์ score_overrides แล้วค่อยนำมารวมกันตอนอ่าน จึงย้อนดูได้ตลอดว่า
 * AI ให้เท่าไร ใครปรับเป็นเท่าไร เมื่อไร และด้วยเหตุผลอะไร
 * =========================================================================== */

/** ข้อมูลเกณฑ์ข้อหนึ่งจากรหัสข้อ (คืน null ถ้าไม่มีข้อนี้ในเกณฑ์) */
function ai_rubric_item($id) {
    foreach (ai_rubric() as $it) {
        if ((string)$it['id'] === (string)$id) return $it;
    }
    return null;
}

/**
 * ฐานข้อมูลนี้มีคอลัมน์ score_overrides (คะแนนที่ถูกปรับรายข้อ) แล้วหรือยัง
 * (auto-migration ใน db_config.php เติมให้อัตโนมัติ ฟังก์ชันนี้ไว้กันกรณีเติมไม่สำเร็จ)
 */
function ai_feedback_has_override_column(PDO $pdo) {
    static $has = null;
    if ($has !== null) return $has;
    try {
        $st = $pdo->query("SHOW COLUMNS FROM essay_ai_feedback LIKE 'score_overrides'");
        $has = ($st && $st->rowCount() > 0);
    } catch (Exception $e) {
        $has = false;
    }
    return $has;
}

/**
 * ล้างข้อมูลคะแนนที่ถูกปรับให้เหลือเฉพาะข้อที่ AI ตรวจได้ และอยู่ในรูปแบบที่ระบบใช้ได้
 * ข้อที่ครูให้เอง (4.3) ไม่ผ่านทางนี้ — มีช่องกรอกของตัวเองอยู่แล้วในคอลัมน์ teacher_scores
 */
function ai_clean_score_overrides($raw) {
    if (is_string($raw)) {
        $decoded = json_decode($raw, true);
        $raw = is_array($decoded) ? $decoded : [];
    }
    if (!is_array($raw)) return [];

    $out = [];
    foreach (ai_rubric() as $it) {
        if (!$it['ai']) continue;
        $ov = isset($raw[$it['id']]) ? $raw[$it['id']] : null;
        if (!is_array($ov) || !isset($ov['raw']) || !is_numeric($ov['raw'])) continue;

        $rawScore = (float)$ov['raw'];
        if ($rawScore < 0) $rawScore = 0;
        if ($rawScore > 4) $rawScore = 4;

        $out[$it['id']] = [
            'raw'      => $rawScore,
            'weighted' => round($rawScore * $it['multiplier'], 2),
            'max'      => $it['max'],
            // teacher = ครูปรับเอง, ai_recheck = สั่งให้ AI ตรวจเฉพาะข้อนี้ใหม่
            'source'   => ((string)($ov['source'] ?? '') === 'ai_recheck') ? 'ai_recheck' : 'teacher',
            'reason'   => ai_clean_text($ov['reason'] ?? '', 800),
            // คำสั่งเพิ่มเติมที่ครูพิมพ์ให้ AI ตอนสั่งตรวจข้อนี้ใหม่ (เก็บไว้ตรวจสอบย้อนหลังได้)
            'instruction' => ai_clean_text($ov['instruction'] ?? '', 800),
            'issue'       => ai_clean_text($ov['issue'] ?? '', 800),
            'suggestion'  => ai_clean_text($ov['suggestion'] ?? '', 800),
            'example'     => ai_clean_text($ov['example'] ?? '', 400),
            'by'          => mb_substr((string)($ov['by'] ?? ''), 0, 50, 'UTF-8'),
            'at'          => mb_substr((string)($ov['at'] ?? ''), 0, 19, 'UTF-8'),
            'model'       => mb_substr((string)($ov['model'] ?? ''), 0, 100, 'UTF-8'),
        ];
    }
    return $out;
}

/**
 * รวมคะแนนที่ AI ให้ไว้กับคะแนนที่ถูกปรับรายข้อ ให้กลายเป็น "คะแนนที่ใช้จริง"
 *
 * $data = ผลตรวจ 1 ชุด (ต้องมีคีย์ scores / total_score / max_score / quality_level)
 * คืนชุดเดิมที่ scores, total_score, quality_level เป็นค่าหลังปรับแล้ว
 * พร้อมแนบคะแนนดั้งเดิมของ AI ไว้ในคีย์ ai_scores / ai_total_score / ai_quality_level
 */
function ai_apply_score_overrides(array $data, $overrides) {
    $ovs    = ai_clean_score_overrides($overrides);
    $scores = (isset($data['scores']) && is_array($data['scores'])) ? $data['scores'] : [];

    // คะแนนดั้งเดิมของ AI ต้องอ่านได้เสมอ แม้ไม่มีการปรับ — รายงานวิจัยใช้เทียบว่าครูปรับไปเท่าไร
    $data['ai_scores']        = $scores;
    $data['ai_total_score']   = round((float)($data['total_score'] ?? 0), 2);
    $data['ai_quality_level'] = (string)($data['quality_level'] ?? '');
    $data['score_overrides']  = $ovs;
    $data['override_count']   = count($ovs);
    if (!$ovs || !$scores) return $data;

    $total  = 0.0;
    $graded = 0;
    foreach (ai_rubric() as $it) {
        if (!$it['ai']) continue;
        $id = $it['id'];
        if (!isset($scores[$id]) || !is_array($scores[$id])) continue;
        if (isset($ovs[$id])) {
            $ov = $ovs[$id];
            // เก็บคะแนนเดิมของ AI ไว้ในแถวเดียวกัน หน้าเว็บจะได้แสดงคู่กันว่า AI ให้เท่าไร ปรับเป็นเท่าไร
            $scores[$id]['ai_raw']      = (float)($scores[$id]['raw'] ?? 0);
            $scores[$id]['ai_weighted'] = (float)($scores[$id]['weighted'] ?? 0);
            $scores[$id]['ai_reason']   = (string)($scores[$id]['reason'] ?? '');
            $scores[$id]['raw']         = $ov['raw'];
            $scores[$id]['weighted']    = $ov['weighted'];
            if ($ov['reason'] !== '') $scores[$id]['reason'] = $ov['reason'];
            $scores[$id]['overridden']  = true;
            $scores[$id]['override']    = $ov;
        }
        $total += (float)$scores[$id]['weighted'];
        $graded++;
    }

    $max = (float)($data['max_score'] ?? ai_rubric_max());
    $data['scores']      = $scores;
    $data['total_score'] = round($total, 2);
    // ระดับคุณภาพคิดบนสเกลเต็ม 60 เหมือนตอน AI ตรวจครั้งแรก (เทียบสัดส่วนจากข้อที่ AI ตรวจได้)
    $data['quality_level'] = ($graded > 0 && $max > 0)
        ? ai_quality_level(($total / $max) * 60)
        : (string)($data['quality_level'] ?? '');

    // ข้อที่สั่งให้ AI ตรวจใหม่ ได้ข้อความ "บกพร่องอะไร / แก้อย่างไร" ชุดใหม่มาด้วย
    // ต้องแทนที่การ์ดเดิมของข้อนั้น ไม่เช่นนั้นครูจะเห็นคะแนนใหม่คู่กับคำอธิบายของรอบที่ถูกแทนที่ไปแล้ว
    $imps = (isset($data['improvements']) && is_array($data['improvements'])) ? $data['improvements'] : [];
    foreach ($ovs as $id => $ov) {
        if ($ov['issue'] === '' && $ov['suggestion'] === '') continue;
        $card = [
            'criterion'  => (string)$id,
            'issue'      => $ov['issue'],
            'suggestion' => $ov['suggestion'],
            'example'    => $ov['example'],
            'from_recheck' => ($ov['source'] === 'ai_recheck'),
        ];
        $replaced = false;
        foreach ($imps as $i => $im) {
            if (is_array($im) && (string)($im['criterion'] ?? '') === (string)$id) {
                $imps[$i]  = $card;
                $replaced  = true;
                break;
            }
        }
        if (!$replaced) $imps[] = $card;
    }
    $data['improvements'] = $imps;

    return $data;
}


/**
 * ย่อ "ฉบับตั้งต้น" ให้เหลือเฉพาะสิ่งที่ต้องใช้เทียบ แล้วเก็บเป็น JSON ในคอลัมน์ baseline_snapshot
 * เก็บคะแนนรายข้อ จุดที่เคยแจ้งให้แก้ และลายนิ้วมือของข้อความ (ไว้ดูว่านักเรียนเขียนใหม่จริงหรือลอกฉบับเดิมมา)
 * ไม่เก็บตัวเรียงความทั้งก้อน เพราะอ่านจากตาราง student_essays ได้อยู่แล้ว
 */
function ai_baseline_snapshot($phase, array $data, $reviewedAt, $wordCount = 0, $textHash = '', array $parts = [], $topic = '') {
    $scores = [];
    $rawScores = (isset($data['scores']) && is_array($data['scores'])) ? $data['scores'] : [];
    foreach ($rawScores as $id => $sc) {
        if (!is_array($sc)) continue;
        $scores[(string)$id] = [
            'raw'      => (float)($sc['raw'] ?? 0),
            'weighted' => (float)($sc['weighted'] ?? 0),
            'max'      => (float)($sc['max'] ?? 0),
            'name'     => (string)($sc['name'] ?? ''),
        ];
    }
    $imps = [];
    $rawImps = (isset($data['improvements']) && is_array($data['improvements'])) ? $data['improvements'] : [];
    foreach ($rawImps as $im) {
        if (!is_array($im)) continue;
        $imps[] = [
            'criterion'  => (string)($im['criterion'] ?? ''),
            'issue'      => (string)($im['issue'] ?? ''),
            'suggestion' => (string)($im['suggestion'] ?? ''),
        ];
    }
    return [
        'phase'         => (string)$phase,
        'label'         => ai_phase_label($phase),
        'short'         => ai_phase_short($phase),
        // หัวข้อของฉบับตั้งต้น — คู่ "คนละหัวข้อ" (หลังเรียน↔ก่อนเรียน) ต้องบอก AI ว่าฉบับเดิมเขียนหัวข้ออะไร
        'topic'         => (string)$topic,
        'reviewed_at'   => (string)$reviewedAt,
        'word_count'    => (int)$wordCount,
        'text_hash'     => (string)$textHash,
        // ข้อความรายส่วนของฉบับตั้งต้น (คำนำ/ย่อหน้า/สรุป) ไว้เทียบว่าฉบับใหม่แก้ตรงไหนไปบ้าง
        'parts'         => $parts,
        'scores'        => $scores,
        'improvements'  => $imps,
        'total_score'   => (float)($data['total_score'] ?? 0),
        'max_score'     => (float)($data['max_score'] ?? ai_rubric_max()),
        'quality_level' => (string)($data['quality_level'] ?? ''),
    ];
}

/**
 * เทียบฉบับที่กำลังดูอยู่กับ "ฉบับตั้งต้น" ตามคู่ที่ครูกำหนด แล้วสรุปว่าคะแนนดีขึ้นจริงไหม
 * คิดจากคะแนนที่เก็บไว้เสมอ (ไม่ต้องพึ่งคำบรรยายของ AI) จึงได้ผลเหมือนกันทั้งตอนตรวจใหม่และตอนเปิดดูย้อนหลัง
 * คืน ['has_baseline' => false] เมื่อรอบนี้ไม่มีคู่เทียบ หรือฉบับตั้งต้นยังไม่ถูกตรวจ
 *
 * ค่าที่ใช้บอกครูว่า "ผิดคาด" มี 3 ตัว
 *   improved   = คะแนนรวมสูงขึ้นจากฉบับตั้งต้นหรือไม่ (สิ่งที่ควรเกิด)
 *   identical  = คะแนนรวมและคะแนนรายข้อเท่ากันหมด (น่าสงสัยว่า AI ไม่ได้เทียบจริง หรือนักเรียนไม่ได้แก้)
 *   same_text  = ข้อความทั้งฉบับเหมือนฉบับตั้งต้นทุกตัวอักษร (นักเรียนคัดลอกมา ยังไม่ได้เขียนใหม่)
 *
 * kind บอกว่าคู่นี้เทียบกันแบบไหน (ดู ai_baseline_kind)
 *   'revision' = ร่าง 2 เทียบร่าง 1 หัวข้อเดียวกัน → เทียบตัวข้อความว่าแก้ตรงไหนได้
 *   'newtopic' = หลังเรียน เทียบ ก่อนเรียน คนละหัวข้อ → เทียบเฉพาะคุณภาพเนื้อหาตามเกณฑ์
 *                จึงไม่มีรายการ "ส่วนที่ถูกแก้" เพราะเป็นงานเขียนคนละชิ้น ไม่ใช่การแก้ร่างเดิม
 */
function ai_draft_progress(array $curr, $baseline, $currentHash = '', $currentWords = 0, array $edits = [], $editsLive = false) {
    $phase   = (string)($curr['essay_phase'] ?? '');
    $basePh  = ai_baseline_phase($phase);
    $kind    = ai_baseline_kind($phase);
    $comment = (string)($curr['draft_comment'] ?? '');
    $changes = (isset($curr['draft_changes']) && is_array($curr['draft_changes'])) ? $curr['draft_changes'] : [];

    // คนละหัวข้อ = เป็นงานเขียนคนละชิ้น ไม่มี "ส่วนที่ถูกแก้" ให้แสดง
    if ($kind === 'newtopic') $edits = [];

    if ($basePh === '') return ['has_baseline' => false, 'pairable' => false];
    if (!is_array($baseline) || empty($baseline['scores'])) {
        return [
            'has_baseline'  => false,
            'pairable'      => true,
            'kind'          => $kind,
            'phase'         => $basePh,
            'label'         => ai_phase_label($basePh),
            'short'         => ai_phase_short($basePh),
        ];
    }

    $baseScores = is_array($baseline['scores']) ? $baseline['scores'] : [];
    $currScores = (isset($curr['scores']) && is_array($curr['scores'])) ? $curr['scores'] : [];

    $noteOf = [];
    foreach ($changes as $ch) {
        $cid = (string)($ch['criterion'] ?? '');
        if ($cid !== '' && !isset($noteOf[$cid])) $noteOf[$cid] = $ch;
    }

    $criteria = [];
    $up = $down = $same = 0;
    foreach (ai_rubric() as $it) {
        if (!$it['ai']) continue;
        $id = $it['id'];
        if (!isset($baseScores[$id]['weighted']) || !isset($currScores[$id]['weighted'])) continue;
        $bw = round((float)$baseScores[$id]['weighted'], 2);
        $cw = round((float)$currScores[$id]['weighted'], 2);
        $delta = round($cw - $bw, 2);
        $dir = ($delta > 0) ? 'up' : (($delta < 0) ? 'down' : 'same');
        if ($dir === 'up') $up++; elseif ($dir === 'down') $down++; else $same++;
        $ch = isset($noteOf[$id]) ? $noteOf[$id] : [];
        $criteria[] = [
            'id'            => $id,
            'name'          => (string)($currScores[$id]['name'] ?? $it['name']),
            'max'           => (float)$it['max'],
            'base_raw'      => (float)($baseScores[$id]['raw'] ?? 0),
            'raw'           => (float)($currScores[$id]['raw'] ?? 0),
            'base_weighted' => $bw,
            'weighted'      => $cw,
            'delta'         => $delta,
            'dir'           => $dir,
            // ข้อความที่ AI ยกมาเทียบให้เห็นว่าเปลี่ยนตรงไหน (ว่างได้ ถ้าโมเดลไม่ได้ตอบมา)
            'before'        => (string)($ch['before'] ?? ''),
            'after'         => (string)($ch['after'] ?? ''),
            'verdict'       => (string)($ch['verdict'] ?? ''),
            'note'          => (string)($ch['note'] ?? ''),
            // AI อธิบายว่าข้อนี้ถูกแก้อะไรไปบ้าง และทำไมคะแนนจึงขยับ
            'added'         => (string)($ch['added'] ?? ''),
            'removed'       => (string)($ch['removed'] ?? ''),
            'reason'        => (string)($ch['reason'] ?? ''),
            'change'        => (string)($ch['change'] ?? ''),
            'changed'       => array_key_exists('changed', $ch) ? $ch['changed'] : null,
        ];
    }

    $baseTotal = round((float)($baseline['total_score'] ?? 0), 2);
    $currTotal = round((float)($curr['total_score'] ?? 0), 2);
    $delta     = round($currTotal - $baseTotal, 2);
    $baseHash  = trim((string)($baseline['text_hash'] ?? ''));
    $currHash  = trim((string)$currentHash);
    $baseQual  = (string)($baseline['quality_level'] ?? '');
    $currQual  = (string)($curr['quality_level'] ?? '');

    return [
        'has_baseline'    => true,
        'pairable'        => true,
        // 'revision' = แก้ร่างเดิม (หัวข้อเดียวกัน) · 'newtopic' = คนละหัวข้อ เทียบที่คุณภาพเนื้อหา
        'kind'            => $kind,
        'phase'           => $basePh,
        'label'           => (string)($baseline['label'] ?? ai_phase_label($basePh)),
        'short'           => (string)($baseline['short'] ?? ai_phase_short($basePh)),
        'this_short'      => ai_phase_short($phase),
        'reviewed_at'     => (string)($baseline['reviewed_at'] ?? ''),
        'base_total'      => $baseTotal,
        'total'           => $currTotal,
        'delta'           => $delta,
        'max_score'       => (float)($curr['max_score'] ?? ai_rubric_max()),
        'base_quality'    => $baseQual,
        'quality'         => $currQual,
        'quality_changed' => ($baseQual !== '' && $currQual !== '' && $baseQual !== $currQual),
        'base_words'      => (int)($baseline['word_count'] ?? 0),
        'words'           => (int)$currentWords,
        'up'              => $up,
        'down'            => $down,
        'same'            => $same,
        'improved'        => ($delta > 0),
        'identical'       => ($delta == 0 && $up === 0 && $down === 0 && $same > 0),
        'same_text'       => ($baseHash !== '' && $currHash !== '' && $baseHash === $currHash),
        'criteria'        => $criteria,
        'comment'         => $comment,
        'changes'         => $changes,
        // ส่วนของเรียงความที่ถูกแก้จริง — ระบบเทียบข้อความเอง ไม่ได้ถาม AI
        'edits'           => array_values($edits),
        'edit_summary'    => ai_edit_summary($edits),
        // true = เทียบจากต้นฉบับ ณ ตอนเปิดดู (ผลตรวจนี้บันทึกไว้ก่อนระบบจะเก็บผลเทียบให้)
        'edits_live'      => (bool)$editsLive,
    ];
}

/* ============================================================
   เทียบ "ตัวข้อความ" ของสองฉบับให้เห็นว่าแก้อะไรไปบ้าง
   ระบบทำเองแบบตรงไปตรงมา (ไม่ต้องพึ่ง AI) จึงเชื่อถือได้ว่าส่วนไหน "ไม่ได้แตะเลย" จริง ๆ
   ผลที่ได้ใช้ 2 ทาง: แนบไปในคำสั่งให้ AI อธิบายได้ตรงจุด และแสดงให้ครู/นักเรียนเห็นในผลตรวจ
   ============================================================ */

/** แยกเรียงความเป็นส่วน ๆ ตามโครงที่ครูกำหนด (คำนำ · เนื้อเรื่องทีละย่อหน้า · สรุป) */
function ai_essay_parts($intro, array $bodyArr, $conclusion) {
    $parts = [['key' => 'intro', 'label' => 'คำนำ', 'text' => trim((string)$intro)]];
    foreach ($bodyArr as $i => $p) {
        $parts[] = [
            'key'   => 'body' . ($i + 1),
            'label' => 'เนื้อเรื่อง ย่อหน้าที่ ' . ($i + 1),
            'text'  => trim((string)$p),
        ];
    }
    $parts[] = ['key' => 'concl', 'label' => 'สรุป', 'text' => trim((string)$conclusion)];
    return $parts;
}

/**
 * ซอยข้อความเป็น "วรรค" ตามการเว้นวรรค
 * ภาษาไทยไม่เว้นวรรคระหว่างคำ แต่เว้นวรรคเพื่อจบความ วรรคจึงเป็นหน่วยที่ใกล้เคียงประโยคที่สุด
 * และเป็นหน่วยที่ยกมาให้ครูอ่านแล้วเข้าใจได้ทันทีว่าข้อความไหนเพิ่มเข้ามาหรือถูกตัดออก
 */
function ai_text_chunks($text) {
    $t = trim(preg_replace('/\s+/u', ' ', (string)$text));
    if ($t === '') return [];
    $out = [];
    foreach (explode(' ', $t) as $c) {
        $c = trim($c);
        if ($c !== '') $out[] = $c;
    }
    return $out;
}

/** นับความยาวของข้อความเป็นคำ (ใช้ตัวตัดคำภาษาไทยของระบบ ไม่ใช่การนับช่องว่าง) */
function ai_count_words($text) {
    if (function_exists('count_thai_words')) return (int)count_thai_words((string)$text);
    return count(ai_text_chunks($text));   // เผื่อกรณีโหลด thai_text_utils.php ไม่สำเร็จ
}

/**
 * เทียบเรียงความสองฉบับทีละส่วน แล้วบอกว่าแต่ละส่วน "เหมือนเดิม / แก้ไข / เพิ่มใหม่ / ถูกตัดออก"
 * ส่วนที่แก้ไขจะบอกด้วยว่ามีข้อความใดเพิ่มเข้ามาและข้อความใดหายไป
 * คืนค่า: [['key','label','status','base_words','words','added'=>[],'removed'=>[]], ...]
 */
function ai_diff_essay_parts(array $baseParts, array $currParts) {
    $index = function (array $parts) {
        $m = [];
        foreach ($parts as $p) $m[$p['key']] = $p;
        return $m;
    };
    $baseMap = $index($baseParts);
    $currMap = $index($currParts);

    // เรียงตามลำดับของฉบับใหม่ก่อน แล้วต่อท้ายด้วยส่วนที่มีเฉพาะในฉบับตั้งต้น (= ถูกตัดออก)
    $order = [];
    foreach ($currParts as $p) $order[] = $p['key'];
    foreach ($baseParts as $p) if (!in_array($p['key'], $order, true)) $order[] = $p['key'];

    $trim = function (array $list) {
        $out = [];
        foreach (array_slice($list, 0, 6) as $c) $out[] = ai_clean_text($c, 160);
        return $out;
    };

    $edits = [];
    foreach ($order as $key) {
        $b = isset($baseMap[$key]) ? (string)$baseMap[$key]['text'] : null;
        $c = isset($currMap[$key]) ? (string)$currMap[$key]['text'] : null;
        $label = isset($currMap[$key]) ? $currMap[$key]['label'] : $baseMap[$key]['label'];

        // ส่วนที่ว่างทั้งสองฝั่ง ไม่ต้องรายงาน (เช่นย่อหน้าที่นักเรียนไม่ได้เขียนทั้งสองฉบับ)
        if (($b === null || $b === '') && ($c === null || $c === '')) continue;

        if ($b === null || $b === '') {
            $edits[] = ['key' => $key, 'label' => $label, 'status' => 'added',
                        'base_words' => 0, 'words' => ai_count_words($c),
                        'added' => $trim(ai_text_chunks($c)), 'removed' => []];
            continue;
        }
        if ($c === null || $c === '') {
            $edits[] = ['key' => $key, 'label' => $label, 'status' => 'removed',
                        'base_words' => ai_count_words($b), 'words' => 0,
                        'added' => [], 'removed' => $trim(ai_text_chunks($b))];
            continue;
        }
        if ($b === $c) {
            $edits[] = ['key' => $key, 'label' => $label, 'status' => 'same',
                        'base_words' => ai_count_words($b), 'words' => ai_count_words($c),
                        'added' => [], 'removed' => []];
            continue;
        }

        $bc = ai_text_chunks($b);
        $cc = ai_text_chunks($c);
        $edits[] = [
            'key' => $key, 'label' => $label, 'status' => 'edited',
            'base_words' => ai_count_words($b), 'words' => ai_count_words($c),
            'added'   => $trim(array_values(array_diff($cc, $bc))),
            'removed' => $trim(array_values(array_diff($bc, $cc))),
        ];
    }
    return $edits;
}

/**
 * ข้อความเรียงความของนักเรียนคนหนึ่ง แยกเป็นส่วน ๆ ทุกรอบงาน: [รหัสรอบงาน => ผลของ ai_essay_parts()]
 * ใช้ส่งเข้า ai_feedback_row_to_array() เพื่อให้เทียบข้อความสองฉบับและวางคู่กันให้ครูอ่านได้
 */
function ai_student_essay_parts(PDO $pdo, $studentId) {
    $out = [];
    if ($studentId === '' || $studentId === null) return $out;
    try {
        $st = $pdo->prepare('SELECT essay_phase, intro_content, body_content, conclusion_content
                               FROM student_essays WHERE student_id = ?');
        $st->execute([$studentId]);
        while ($r = $st->fetch()) {
            $body = json_decode((string)($r['body_content'] ?? ''), true);
            if (!is_array($body)) {
                $body = ($r['body_content'] ?? '') !== '' ? [(string)$r['body_content']] : [];
            }
            $out[$r['essay_phase']] = ai_essay_parts(
                (string)($r['intro_content'] ?? ''), $body, (string)($r['conclusion_content'] ?? '')
            );
        }
    } catch (Exception $e) {
        // อ่านไม่ได้ก็ยังแสดงผลตรวจได้ตามปกติ แค่ไม่มีข้อความให้วางเทียบ
    }
    return $out;
}

/**
 * วางเรียงความสองฉบับคู่กันทีละส่วน เพื่อให้คุณครู "อ่านเทียบ" ได้เต็ม ๆ ว่าเปลี่ยนอะไรไปบ้าง
 *
 * ต่างจาก ai_diff_essay_parts ตรงที่ฟังก์ชันนั้นสรุปเป็นรายการสั้น ๆ ว่าเพิ่ม/ตัดอะไร
 * ส่วนฟังก์ชันนี้คืน "ข้อความเต็มของทั้งสองฉบับ" โดยทำเครื่องหมายไว้ทีละวรรคว่าวรรคไหนเปลี่ยน
 *   ฝั่งฉบับตั้งต้น วรรคที่ทำเครื่องหมาย = วรรคที่หายไปในฉบับใหม่
 *   ฝั่งฉบับนี้     วรรคที่ทำเครื่องหมาย = วรรคที่เพิ่งเพิ่มเข้ามา
 *
 * $markDiff = false สำหรับคู่คนละหัวข้อ (ก่อนเรียน↔หลังเรียน) เพราะเป็นงานเขียนคนละชิ้น
 * การไฮไลต์ว่า "วรรคนี้เพิ่มเข้ามา" จึงไม่มีความหมาย ให้วางคู่กันไว้อ่านเทียบเฉย ๆ
 */
function ai_side_by_side_parts(array $baseParts, array $currParts, $markDiff = true) {
    $index = function (array $parts) {
        $m = [];
        foreach ($parts as $p) $m[$p['key']] = $p;
        return $m;
    };
    $baseMap = $index($baseParts);
    $currMap = $index($currParts);

    $order = [];
    foreach ($currParts as $p) $order[] = $p['key'];
    foreach ($baseParts as $p) if (!in_array($p['key'], $order, true)) $order[] = $p['key'];

    // ทำเครื่องหมายทีละวรรค: วรรคที่ไม่ปรากฏในอีกฉบับหนึ่ง = วรรคที่เปลี่ยน
    $mark = function ($chunks, $otherSet) {
        $out = [];
        foreach ($chunks as $c) {
            $out[] = ['t' => $c, 'd' => !isset($otherSet[$c])];
        }
        return $out;
    };

    $rows = [];
    foreach ($order as $key) {
        $b = isset($baseMap[$key]) ? (string)$baseMap[$key]['text'] : '';
        $c = isset($currMap[$key]) ? (string)$currMap[$key]['text'] : '';
        if (trim($b) === '' && trim($c) === '') continue;

        $label = isset($currMap[$key]) ? $currMap[$key]['label'] : $baseMap[$key]['label'];
        $bc = ai_text_chunks($b);
        $cc = ai_text_chunks($c);

        if (trim($b) === '')      $status = 'added';
        elseif (trim($c) === '')  $status = 'removed';
        elseif ($b === $c)        $status = 'same';
        else                      $status = 'edited';

        $bSet = array_flip($bc);
        $cSet = array_flip($cc);
        $rows[] = [
            'key'        => $key,
            'label'      => $label,
            'status'     => $markDiff ? $status : '',
            'base_words' => ai_count_words($b),
            'words'      => ai_count_words($c),
            // ทำเครื่องหมายรายวรรคเฉพาะส่วนที่ "แก้ไข" เท่านั้น
            // ส่วนที่เพิ่มใหม่/ถูกตัดออกทั้งย่อหน้า ป้ายสถานะบอกอยู่แล้ว ไม่ต้องระบายทั้งย่อหน้าให้อ่านยาก
            'base'       => ($markDiff && $status === 'edited') ? $mark($bc, $cSet) : $mark($bc, $bSet),
            'curr'       => ($markDiff && $status === 'edited') ? $mark($cc, $bSet) : $mark($cc, $cSet),
        ];
    }
    return ['marked' => (bool)$markDiff, 'parts' => $rows];
}

/** นับว่าฉบับนี้แก้ไปกี่ส่วน เพิ่มกี่ส่วน ตัดออกกี่ส่วน และไม่ได้แตะกี่ส่วน */
function ai_edit_summary(array $edits) {
    $sum = ['edited' => 0, 'added' => 0, 'removed' => 0, 'same' => 0, 'total' => count($edits)];
    foreach ($edits as $e) {
        $st = (string)($e['status'] ?? '');
        if (isset($sum[$st])) $sum[$st]++;
    }
    $sum['touched'] = $sum['edited'] + $sum['added'] + $sum['removed'];
    return $sum;
}

/** สรุปผลเทียบข้อความเป็นบรรทัดภาษาไทย สำหรับแนบไปในคำสั่งที่ส่งให้ AI */
function ai_edit_lines(array $edits) {
    $lines = [];
    foreach ($edits as $e) {
        if ($e['status'] === 'same') {
            $lines[] = '- ' . $e['label'] . ': เหมือนฉบับตั้งต้นทุกตัวอักษร (ไม่ได้แก้เลย)';
            continue;
        }
        if ($e['status'] === 'added') {
            $lines[] = '- ' . $e['label'] . ': เพิ่มเข้ามาใหม่ในฉบับนี้ (' . (int)$e['words'] . ' คำ)';
            continue;
        }
        if ($e['status'] === 'removed') {
            $lines[] = '- ' . $e['label'] . ': มีในฉบับตั้งต้นแต่ถูกตัดออกจากฉบับนี้ (เดิม ' . (int)$e['base_words'] . ' คำ)';
            continue;
        }
        $l = '- ' . $e['label'] . ': แก้ไข (จาก ' . (int)$e['base_words'] . ' คำ เป็น ' . (int)$e['words'] . ' คำ)';
        if ($e['added'])   $l .= "\n    ข้อความที่เพิ่มเข้ามา: " . implode(' / ', $e['added']);
        if ($e['removed']) $l .= "\n    ข้อความที่ถูกตัดออก: " . implode(' / ', $e['removed']);
        $lines[] = $l;
    }
    return $lines;
}

/**
 * ลายนิ้วมือของเนื้อหาเรียงความ 1 ฉบับ (ส่วนนำ + เนื้อเรื่องทุกย่อหน้า + สรุป)
 * ใช้เทียบว่าต้นฉบับถูกแก้ไขไปจากตอนที่ AI ตรวจไว้หรือไม่ — ถ้าเหมือนเดิมเป๊ะ ไม่ต้องตรวจใหม่
 * ไม่รวบช่องว่างให้ เพราะการเว้นวรรคเป็นเกณฑ์การให้คะแนนข้อ 4.2 อยู่แล้ว
 */
function ai_essay_hash($intro, $bodyArr, $conclusion) {
    if (!is_array($bodyArr)) {
        $bodyArr = ($bodyArr === null || $bodyArr === '') ? [] : [(string)$bodyArr];
    }
    $parts = array_merge(
        [trim((string)$intro)],
        array_map(function ($p) { return trim((string)$p); }, $bodyArr),
        [trim((string)$conclusion)]
    );
    return sha1(implode("\x1f", $parts));
}

/**
 * นักเรียนบันทึกต้นฉบับใหม่ → ถ้าเรียงความฉบับนี้เคยให้ AI ตรวจไว้แล้วและเนื้อหาเปลี่ยนไปจริง
 * ให้ทำเครื่องหมาย "รอตรวจใหม่" ไว้ในผลตรวจเดิม เพื่อเข้าคิวให้คุณครูสั่ง AI ตรวจซ้ำ
 * ถ้านักเรียนแก้แล้วย้อนกลับมาเหมือนเดิมเป๊ะ ระบบจะถอดออกจากคิวให้เอง
 * คืนค่า true เมื่อฉบับนี้ถูกจัดเข้าคิวตรวจใหม่
 */
function ai_mark_essay_recheck(PDO $pdo, $studentId, $phase, $hash) {
    try {
        $stmt = $pdo->prepare('SELECT essay_hash FROM essay_ai_feedback WHERE student_id = ? AND essay_phase = ?');
        $stmt->execute([$studentId, $phase]);
        $row = $stmt->fetch();
        if (!$row) return false;   // ยังไม่เคยให้ AI ตรวจฉบับนี้ — ไม่มีอะไรต้องเข้าคิว

        // ผลตรวจเก่าที่บันทึกไว้ก่อนมีระบบคิว (ไม่มีลายนิ้วมือ) ถือว่าต้องตรวจใหม่ไว้ก่อน
        $old  = (string)($row['essay_hash'] ?? '');
        $same = ($old !== '' && $old === $hash);

        $upd = $pdo->prepare('
            UPDATE essay_ai_feedback
               SET recheck_needed = ?, recheck_marked_at = ?
             WHERE student_id = ? AND essay_phase = ?
        ');
        $upd->execute([$same ? 0 : 1, $same ? null : date('Y-m-d H:i:s'), $studentId, $phase]);
        return !$same;
    } catch (Exception $e) {
        return false;   // ฐานข้อมูลยังไม่มีคอลัมน์คิว — ไม่ควรทำให้การบันทึกเรียงความพัง
    }
}

/** นับจำนวนครั้งที่ผู้ใช้คนนี้เรียก AI ไปแล้ววันนี้ (กันการกดรัวจนโควตาฟรีหมด) */
function ai_usage_today(PDO $pdo, $userId) {
    try {
        // นับเฉพาะครั้งที่ตรวจสำเร็จ — ครั้งที่ตรวจไม่ผ่านถือว่ายังไม่ได้ตรวจ จึงไม่ควรกินโควตาของครู
        $stmt = $pdo->prepare('SELECT COUNT(*) AS c FROM ai_usage_log
                                WHERE user_id = ? AND success = 1 AND created_at >= CURDATE()');
        $stmt->execute([$userId]);
        $row = $stmt->fetch();
        return $row ? (int)$row['c'] : 0;
    } catch (Exception $e) {
        return 0;
    }
}


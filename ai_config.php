/**
 * รอบงาน "ฉบับตั้งต้น" ที่ต้องนำมาเทียบกับรอบงานที่ระบุ
 * คืนค่าว่าง = รอบนี้เป็นฉบับตั้งต้นเสียเอง (ก่อนเรียน / ร่างที่ 1) จึงไม่มีอะไรให้เทียบ
 */
function ai_baseline_phase($phase) {
    $pairs = ai_baseline_pairs();
    return isset($pairs[$phase]) ? $pairs[$phase] : '';
}

/**
 * คู่ที่เทียบกันเป็น "คนละแบบ" กัน ต้องเทียบคนละวิธี
 *
 *   'revision' = ร่างที่ 2 เทียบร่างที่ 1 ของหน่วยเดียวกัน — หัวข้อเดียวกัน เรื่องเดียวกัน
 *                นักเรียนเอางานเดิมมาแก้ จึงเทียบ "ตัวข้อความ" ได้ตรง ๆ ว่าแก้ตรงไหน
 *
 *   'newtopic' = หลังเรียน เทียบ ก่อนเรียน — คนละหัวข้อ คนละเรื่อง เป็นงานเขียนคนละชิ้น
 *                ห้ามเทียบว่า "แก้ข้อความตรงไหน" เพราะไม่ใช่งานชิ้นเดียวกัน
 *                ต้องเทียบที่ "คุณภาพเนื้อหาและความสามารถในการเขียนตามเกณฑ์แต่ละข้อ" เท่านั้น
 *
 * ตัดสินจากรอบหัวข้อจริง (essay_topic_phase) ไม่ได้ฮาร์ดโค้ดไว้
 * ถ้าวันหลังครูเพิ่มคู่เทียบใหม่ ระบบจะแยกประเภทให้ถูกเองโดยไม่ต้องแก้ตรงนี้
 */
function ai_baseline_kind($phase) {
    $base = ai_baseline_phase($phase);
    if ($base === '') return '';
    if (!function_exists('essay_topic_phase')) return 'revision';
    return (essay_topic_phase($phase) === essay_topic_phase($base)) ? 'revision' : 'newtopic';
}

